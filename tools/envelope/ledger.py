"""The prompt-facing section ledger of a segment: header scalars plus one row per 10 mm station, written as YAML and CSV."""
from __future__ import annotations

import csv
import io

import numpy as np
import yaml

from . import field

STATION_MM = 10.0
SHELL_MM = (0.0, 3.0, 5.0, 8.0, 10.0)      # shell thicknesses t reported when the sheet has none (the brief)
DIRECTIONS = (0, 45, 90, 135, 180, 225, 270, 315)   # degrees from +x (anterior) towards +y (left)


def direction_names(side: str):
    """Names of the 8 directions for a segment-frame angle from +x towards +y. y is left, so for the right thigh +y is medial."""
    medial_sign = +1 if side == "right" else -1
    base = {0: "ant", 90: "med" if medial_sign > 0 else "lat", 180: "post", 270: "lat" if medial_sign > 0 else "med"}
    names = {}
    for a in DIRECTIONS:
        if a in base:
            names[a] = base[a]
        else:
            fa = "ant" if a in (45, 315) else "post"
            sa = base[90] if a in (45, 135) else base[270]
            names[a] = f"{fa}_{sa}"
    return names


def stations(length: float):
    s = list(np.arange(0.0, length, STATION_MM))
    s.append(float(length))
    return [float(x) for x in s]


def rows_for(seg: field.Segment, side: str, shells=SHELL_MM):
    names = direction_names(side)
    dirs = {"ant": 0, "post": 180}
    dirs["med" if side == "right" else "lat"] = 90
    dirs["lat" if side == "right" else "med"] = 270
    out = []
    for s in stations(seg.length):
        sec = seg.section(s)
        cx, cy, r = sec.chebyshev(0.0)
        area = sec.area(0.0)
        row = {"s_mm": round(s, 1), "area_mm2": round(area, 1), "perimeter_mm": round(sec.perimeter(0.0), 1),
               "perimeter_equiv_circle_mm": round(2 * float(np.sqrt(np.pi * area)), 1),
               "cheb_cx_mm": round(cx, 2), "cheb_cy_mm": round(cy, 2), "cheb_r_mm": round(r, 2)}
        for nm in ("ant", "post", "med", "lat"):
            row[f"hw_{nm}_mm"] = round(sec.ray((0.0, 0.0), dirs[nm]), 2)
        for a in DIRECTIONS:
            row[f"r_{names[a]}_mm"] = round(sec.ray((cx, cy), a), 2) if np.isfinite(cx) else float("nan")
        for t in shells:
            if t == 0.0:
                continue
            tag = f"t{t:g}"
            row[f"area_{tag}_mm2"] = round(sec.area(t), 1)
            row[f"cheb_r_{tag}_mm"] = round(sec.chebyshev(t)[2], 2)
        out.append(row)
    return out


def header(res, rows, shells, density_note, mesh_label, ansur_label, inputs_sha, hip_zone_mm) -> dict:
    """Header scalars of a segment ledger. `hip_zone_mm` is the proximal zone reported apart (the thigh's; 0 or None for other segments)."""
    seg, reg = res.seg, res.reg
    skin = seg.volume(0.0)
    zone = hip_zone_mm if (res.name == "thigh" and hip_zone_mm) else 0.0
    body = [r for r in rows if r["s_mm"] >= zone] or rows
    hip = [r for r in rows if r["s_mm"] < zone]
    summ = reg.summary()

    def minrow(rs, key):
        r = min(rs, key=lambda x: x[key])
        return {"r_mm": r[key], "station_mm": r["s_mm"]}

    st = summ["stretch"]
    mass = getattr(res, "mass_kg", None)
    return {
        "segment": f"{res.name}_R",
        "frame": "segment: origin at the proximal joint centre on the vertical axis, z up (distal end at z = -length), x anterior, y left; stations are distances below the origin",
        "length_mm": round(seg.length, 2),
        "stretch": {k: round(v, 5) for k, v in st.items()},
        "shear_mm": {k: round(v, 2) for k, v in summ["shear_mm"].items()},
        "shear_deg": {k: round(v, 2) for k, v in summ["shear_deg"].items()},
        "pelvis_scale_k": round(reg.sheet.k_pelvis, 5),
        "mesh_nodes_mm": {k: round(v, 2) for k, v in summ["mesh_nodes_mm"].items()},
        "sheet_nodes_mm": {k: round(v, 2) for k, v in summ["sheet_nodes_mm"].items()},
        "knee_source": reg.knee_source,
        "mesh_file": mesh_label,
        "ansur_source": ansur_label,
        "voxel_mm": seg.h,
        "skin_volume_l": round(skin / 1e6, 4),
        "inner_volume_l": {f"t{t:g}": round(seg.volume(t) / 1e6, 4) for t in shells},
        "skin_volume_excluding_hip_zone_l": round(seg.volume(0.0, zone, None) / 1e6, 4) if zone else None,
        "sheet_mass_kg": round(mass, 4) if mass else None,
        "min_inscribed_radius": {
            "outside_hip_zone": {**minrow(body, "cheb_r_mm"), "from_station_mm": zone},
            "hip_zone": {**minrow(hip, "cheb_r_mm"), "below_station_mm": zone} if hip else None,
        },
        "min_inscribed_radius_inner": {f"t{t:g}": minrow(body, f"cheb_r_t{t:g}_mm") for t in shells if t != 0.0},
        "directions": {str(a): n for a, n in direction_names("right").items()},
        "sections_csv": f"{res.name}_R_sections.csv",
        "inputs_sha256_12": inputs_sha,
    }


def banner(tool, inputs_sha, comment="#"):
    return f"{comment} GENERATED by {tool} from the mesh, the landmark file, the sheet pull and the parameters (inputs sha256:{inputs_sha}). Do not edit; change the inputs and rebuild.\n"


def to_yaml(hdr: dict, inputs_sha: str) -> str:
    return banner("fy envelope build", inputs_sha) + yaml.safe_dump(hdr, sort_keys=True, default_flow_style=False, allow_unicode=True)


def to_csv(rows, inputs_sha: str) -> str:
    buf = io.StringIO()
    buf.write(banner("fy envelope build", inputs_sha))
    w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()), lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()
