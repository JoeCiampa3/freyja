"""
Rendering of the thread's generated outputs from a finished Build: the banner (CONVENTIONS section 4), the derived JSON, the dossier and
STATUS.md. Pure functions of the build; nothing here reads the disk or the clock. Everything is sorted and LF-terminated.

Part A of the Stage 3a brief needs the dossier sections 1 to 6 because the reallocation test asserts which dossier files change. The
references and neighbourhood sections (7 and 8) and the link check are T5.
"""
from __future__ import annotations

import json

from . import addr, edges

TOOL = "tools/thread (fy thread build)"
FROM = "thread/records, thread/stamps, decisions, params/snapshot.csv and sim/models/freyja.xml"
SHOW_CHARS = 100  # a value in STATUS.md or a dossier is shown at most this long; `fy thread why` shows it whole
KIND_TITLES = {"segment": "segments", "joint": "joints", "part": "parts", "interface": "interfaces", "load_case": "load cases",
               "harness_run": "harness runs", "work_item": "work items"}
REFERENCE_FIELDS = {"housed_in", "acts_across", "reacts_into", "harness", "between", "carries_cut_of", "path", "of", "superseded_by"}


def json_bytes(doc: dict, banner: tuple) -> bytes:
    out = dict(doc)
    out["generated_by"], out["inputs"] = banner
    return (json.dumps(out, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


def short(value) -> str:
    text = addr.canonical(value)
    return text if len(text) <= SHOW_CHARS else text[:SHOW_CHARS - 3] + "..."


def shown(value, hash=None) -> str:
    if value is None:
        return f"(not stored, hash {hash})" if hash else "(does not resolve)"
    return f"`{short(value)}`"


class Context:
    def __init__(self, b):
        self.b = b
        self.snap = b.store.snapshot_sha

    def banner(self, path: str) -> tuple:
        text = f"GENERATED by {TOOL} from {FROM} (snapshot sha256:{self.snap}). Do not edit; change the inputs and rebuild."
        return text, f"sha256:{self.b.input_hashes[path]}"

    def md_banner(self, path: str) -> str:
        return f"<!-- GENERATED by {TOOL} from {FROM} (snapshot sha256:{self.snap}), inputs sha256:{self.b.input_hashes[path]}. Do not edit; change the inputs and rebuild. -->\n"

    def link(self, id: str) -> str:
        return f"[{id}]({id}.md)" if id in self.b.docs else f"`{id}`"

    # ---- one record's dossier -------------------------------------------------------------

    def dossier(self, id: str) -> bytes:
        d = self.b.docs[id]
        k = d["kind"]
        L = [self.md_banner(f"thread/dossiers/{id}.md").rstrip("\n"), "", f"# {id}", ""]
        flag = {"proposed": " (PROPOSED: not yet accepted)", "superseded": f" (SUPERSEDED by {self.link(d.get('superseded_by', ''))})"}.get(d["status"], "")
        L += [f"Kind: {k}. Status: **{d['status']}**{flag}.", "", d["purpose"], ""]
        if d.get("notes"):
            L += [f"Notes: {d['notes']}", ""]
        L += ["## Binding and values", ""]
        if k == "segment":
            L += [f"Model bodies: {', '.join(f'`{b}`' for b in d['bound_bodies'])}. Values are read from the right side for a bilateral segment.", ""]
            L += self._table(d["values"], "snapshot key")
        elif k == "joint":
            L += [f"Model hinges: {', '.join(f'`{h}`' for h in d['bound_hinges'])}.",
                  f"Parent segments: {self._links(d['parent_segments'])}. Child segments: {self._links(d['child_segments'])}.", ""]
            L += self._table(d["rom"], "ROM key")
            if d["rom_missing"]:
                L += [f"Not in the snapshot (the sheet has no value, so the hinge is unlimited): {', '.join(f'`{x}`' for x in d['rom_missing'])}.", ""]
        else:
            L += ["No model or snapshot binding.", ""]
        L += ["## Relations", ""]
        L += ["Authored:", ""]
        authored = [(f, d[f]) for f in sorted(d) if f in REFERENCE_FIELDS]
        for f, v in authored:
            L.append(f"- {f}: {self._links(v) if isinstance(v, list) else self.link(v)}")
        for f in sorted(d):
            if f in REFERENCE_FIELDS or f in ("id", "kind", "status", "purpose", "notes", "superseded_by") or f in self._derived_keys(d) or f in (
                    "work", "decisions", "budgets", "values", "rom", "rom_missing", "bound_bodies", "bound_hinges"):
                continue
            L.append(f"- {f}: `{addr.canonical(d[f])}`")
        if not authored and not any(f not in REFERENCE_FIELDS for f in d):
            L.append("- none")
        L += ["", "Derived:", ""]
        derived = [n for n in sorted(self._derived_keys(d))]
        for n in derived:
            L.append(f"- {n}: {self._links(d[n]) if d[n] else 'none'}")
        if not derived:
            L.append("- none")
        L += ["", "## Budgets", ""]
        if "budgets" in d:
            m = d["budgets"]["mass"]
            L += [self._mass_line(m)]
            for c in m["claims"]:
                L.append(f"  - {self.link(c['part'])}: {c['kg']} kg x {c['count']}")
            L.append("")
        else:
            L += ["None.", ""]
        L += ["## Work", ""]
        if k == "work_item":
            w = d["work"]
            L += [f"Status: **{w['status']}**" + (f" (baseline stamp {w['stamp']}{', pinned' if w['pinned'] else ''})" if w["stamp"] else " (no stamp yet)") + ".",
                  f"Owner: {self.link(d['of'])}. Mode: {d['mode']}."]
            for m in w["moved"]:
                L.append(f"- moved: `{m['address']}`: stamped {shown(m['stamped'], m['stamped_hash'])}, now {shown(m['current'], m['current_hash'])}")
            L.append("")
        elif d["work"]:
            for w in d["work"]:
                L.append(f"- {self.link(w['id'])}: {w['status']} ({' and '.join(w['role'])})")
            L.append("")
        else:
            L += ["None.", ""]
        L += ["## Decisions", ""]
        L += [f"- {x['id']} ({x['status']})" for x in d["decisions"]] or ["None."]
        L.append("")
        return ("\n".join(L).rstrip("\n") + "\n").encode("utf-8")

    def _derived_keys(self, d):
        return [n for n, t in edges.BY_NAME.items() if t.origin == "derived" and n in d]

    def _links(self, ids) -> str:
        return ", ".join(self.link(i) for i in ids) if ids else "none"

    def _table(self, rows: dict, head: str) -> list:
        if not rows:
            return ["No values.", ""]
        return [f"| {head} | value | sheet source |", "|---|---|---|"] + [f"| `{k}` | {v['value']} | {v['sheet_source']} |" for k, v in sorted(rows.items())] + [""]

    def _mass_line(self, m: dict) -> str:
        if m["target_kg"] is None:
            return f"Mass: the parts claim {m['claimed_kg']} kg; the snapshot has no target for this segment."
        return (f"Mass: target {m['target_kg']} kg, claimed {m['claimed_kg']} kg, remaining {m['remaining_kg']} kg"
                + (" (**OVER**)." if m["over"] else "."))

    # ---- STATUS.md ------------------------------------------------------------------------

    def status(self) -> bytes:
        b = self.b
        by_kind = {}
        for r in b.recs.values():
            by_kind[r["kind"]] = by_kind.get(r["kind"], 0) + 1
        rework = [(i, w) for i, w in sorted(b.work.items()) if w["status"] in ("stale", "drifted", "unknown")]
        counts = ", ".join(f"{n} {KIND_TITLES[k]}" for k, n in sorted(by_kind.items()))
        L = [self.md_banner("thread/STATUS.md").rstrip("\n"), "", "# Thread status", "",
             f"{len(b.recs)} records | {len(b.work)} work items | rework {len(rework)} | errors {len(b.errors)} | warnings {len(b.warnings)}", ""]
        if counts:
            L += [f"Records: {counts}.", ""]
        L += ["## Rework queue", ""]
        if not rework:
            L += ["Nothing to rework.", ""]
        for i, w in rework:
            L += [f"### {i}: {w['status']}" + (f" (baseline {w['stamp']}{', pinned' if w['pinned'] else ''})" if w["stamp"] else ""), ""]
            for m in w["moved"]:
                L.append(f"- `{m['address']}`: stamped {shown(m['stamped'], m['stamped_hash'])}, now {shown(m['current'], m['current_hash'])}")
            L.append("")
        L += ["## Budgets", "", "| segment | target kg | claimed kg | remaining kg | |", "|---|---|---|---|---|"]
        for i, m in sorted(b.budgets["segments"].items()):
            L.append(f"| {i} | {self._num(m['target_kg'])} | {m['claimed_kg']} | {self._num(m['remaining_kg'])} | {'OVER' if m['over'] else ''} |")
        bd = b.budgets["body"]
        L.append(f"| whole body | {self._num(bd['target_kg'])} | {bd['claimed_kg']} | | {'OVER' if bd['over'] else ''} |")
        L += ["", "Mass is the one budget so far. A bilateral segment is compared on its right side; the whole body counts each bilateral claim twice.", ""]
        L += ["## Proposed records", ""]
        proposed = [f"- {self.link(i).replace('](', '](dossiers/')} ({r['kind']})" for i, r in sorted(b.recs.items()) if r["status"] == "proposed"]
        L += proposed or ["None."]
        L += ["", "## Problems", ""]
        probs = sorted(b.issues, key=lambda i: (i.level, i.code, i.ids, i.message))
        L += [f"- {i.level} {i.code}: {i.message}" for i in probs] or ["None."]
        L.append("")
        return ("\n".join(L).rstrip("\n") + "\n").encode("utf-8")

    @staticmethod
    def _num(x):
        return "none" if x is None else x
