"""
Stage 2 T8: `fy state` writes docs/STATE.md, so that anyone reading a copy of the repo can tell exactly which state it is and
whether it is stale. Every line comes from a tool, never from typing. Deterministic: no timestamps, sorted listings.

    fy state [--no-run | --rerun]

--no-run records the tests and checks as not run. Without it the checks always run, and the suite runs unless the tree is the one the
last full run saw (tools/testkit: the tree key, which leaves out docs/STATE.md and docs/memos/); the Tests section then says the result
is reported from that run. --rerun runs the suite regardless, including the tests that would be skipped on unchanged inputs. Any other
argument is an error and nothing runs. The tracked-file count and the dirty hash leave out docs/STATE.md itself, otherwise the file would
describe itself. The base commit is HEAD at generation; the commit that adds the file is its child, so the file names its parent.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
if str(REPO / "tools") not in sys.path:
    sys.path.insert(0, str(REPO / "tools"))

import testkit  # noqa: E402

STATE_FILE = "docs/STATE.md"
MAX_LINES = 119
GENERATED = "GENERATED by tools/state from git, CLAUDE.md, params/snapshot.meta.json, run records and check results (snapshot sha256:{snap}). Do not edit; rerun `fy state`."
EXCLUDE = f":(exclude){STATE_FILE}"


def _git(root, *args) -> str:
    return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True, text=True, encoding="utf-8").stdout


def _git_bytes(root, *args) -> bytes:
    return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True).stdout


class BriefLinesError(ValueError):
    """CLAUDE.md does not carry the per-track brief lines this tool reads."""


BRIEF_LINE = re.compile(r"^Current (\w+) brief:\s*`([^`]+)`", re.MULTILINE)


def briefs(root) -> dict:
    """track (lower case) -> brief path, from the `Current <track> brief: `path`` lines of CLAUDE.md, sorted by track."""
    found = {}
    for m in BRIEF_LINE.finditer((Path(root) / "CLAUDE.md").read_text(encoding="utf-8")):
        track = m.group(1).lower()
        if track in found:
            raise BriefLinesError(f"CLAUDE.md names two 'Current {m.group(1)} brief:' lines; each track has exactly one")
        found[track] = m.group(2)
    if not found:
        raise BriefLinesError("CLAUDE.md has no line of the form 'Current <track> brief: `path`' (one per track, path in backticks); "
                              "fy state reads one brief hash per track from those lines")
    return dict(sorted(found.items()))


def brief_hash(root, track) -> str:
    """First 12 hex of the sha256 of the track's current brief, bytes with line endings normalised to LF; `missing` when the named file is absent."""
    path = briefs(root)[track]
    if not (Path(root) / path).exists():
        return "missing"
    data = (Path(root) / path).read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()[:12]


def tree_state(root) -> tuple:
    """(dirty, diff hash or None). Dirty is any file other than docs/STATE.md that is untracked or that the working tree differs on (a file merely staged for the commit is clean); the hash is of
    `git diff HEAD` with docs/STATE.md excluded and is None when no tracked file differs (CONVENTIONS section 6)."""
    status = _git(root, "status", "--porcelain", "--untracked-files=all", "--", ".", EXCLUDE)
    diff = _git_bytes(root, "diff", "HEAD", "--", ".", EXCLUDE)
    # Porcelain "XY path": X is the index, Y the working tree. A file staged for the commit (Y blank) is clean; anything the working tree
    # still differs on (Y set) and every untracked file ("??") makes the tree dirty.
    dirty = any(l.startswith("??") or l[1:2] != " " for l in status.splitlines() if l.strip())
    return dirty, (hashlib.sha256(diff).hexdigest()[:12] if diff else None)


def _run_pytest(root, extra=()) -> str:
    """The whole suite the way `fy test` runs it; returns pytest's standard output."""
    parallel = testkit.PARALLEL if testkit.xdist_available() else ()
    return subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", *parallel, *extra], cwd=root, capture_output=True, text=True, encoding="utf-8").stdout


def suite_results(root, rerun=False) -> dict:
    """passed, cached (skipped on unchanged inputs), failed and skipped for the whole suite on this tree. The record of the last full run
    is reported, with `reused` set to its tree key, when the tree is still the one that run saw; otherwise the suite runs."""
    rec = None if rerun else testkit.last_full(root)
    if rec:
        return {**rec["tests"], "reused": rec["tree_key"][:12]}
    (Path(root) / testkit.CACHE_DIR / testkit.LAST_FULL_FILE).unlink(missing_ok=True)  # so that only this run's record can be read below
    stdout = _run_pytest(root, ("--rerun-cached",) if rerun else ())
    rec = testkit.last_full(root)  # written by the run itself (testkit/plugin.py); absent when the run was interrupted or changed the tree
    if rec:
        return dict(rec["tests"])
    tail = stdout.strip().splitlines()[-1] if stdout.strip() else ""
    counts = {k: int(n) for n, k in re.findall(r"(\d+) (passed|failed|skipped|errors|error)", tail)}
    return {"passed": counts.get("passed", 0), "cached": 0, "failed": counts.get("failed", 0) + counts.get("error", 0) + counts.get("errors", 0),
            "skipped": counts.get("skipped", 0)}


def default_runner(root, rerun=False) -> dict:
    """Run the tests and the checks the way `fy test` and `fy check` do."""
    tests = suite_results(root, rerun)
    sys.path[:0] = [str(Path(root) / "checks"), str(Path(root) / "sim" / "scripts")]
    import checklib
    import mjcf_checks  # noqa: F401
    import sim_checks  # noqa: F401
    import thread_checks  # noqa: F401
    report = checklib.run_checks(checklib.Context.from_files(), waivers=checklib.load_waivers())
    return {"tests": tests, "checks": [(r.id, r.tier, r.status) for r in report.results]}


def _waivers(root) -> list:
    path = Path(root) / "checks" / "waivers.yaml"
    if not path.exists():
        return []
    import yaml
    return [(w["check"], bool(w.get("confirmed")), str(w.get("review_by"))) for w in (yaml.safe_load(path.read_text(encoding="utf-8")) or [])]


def _xfails(root) -> list:
    """Every test marked `xfail` in tests/ and checks/, read from the source (no run needed): `path::name | strict | reason`."""
    import ast
    found = []
    for sub in ("checks", "tests"):
        for path in sorted((Path(root) / sub).glob("test_*.py")):
            for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
                if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                for dec in node.decorator_list:
                    call = dec if isinstance(dec, ast.Call) else None
                    if not (isinstance(dec, ast.Attribute) and dec.attr == "xfail" or call and getattr(call.func, "attr", None) == "xfail"):
                        continue
                    kw = {k.arg: k.value for k in call.keywords} if call else {}
                    strict = isinstance(kw.get("strict"), ast.Constant) and kw["strict"].value is True
                    reason = kw["reason"].value if isinstance(kw.get("reason"), ast.Constant) else "(no reason)"
                    found.append(f"{sub}/{path.name}::{node.name} | {'strict' if strict else 'not strict'} | {reason}")
    return found


def _latest_runs(root) -> list:
    d = Path(root) / "sim" / "runs"
    latest = {}
    for p in sorted(d.glob("*/summary.json")) if d.exists() else []:
        s = json.loads(p.read_text(encoding="utf-8"))
        latest[s["scenario"]["name"]] = s["run_id"]  # directory names sort by start time
    return sorted(latest.values())


def _latest_gait(root) -> str:
    """The tracked extract's source record (gait.json is untracked, so a clean clone has none)."""
    p = Path(root) / "sim" / "benchmarks" / "gait_extract.json"
    if not p.exists():
        return "none (sim/benchmarks/gait_extract.json is absent)"
    r = json.loads(p.read_text(encoding="utf-8"))
    return f"{r['gait_id']} | spec sha256:{r['spec_sha256'][:12]} | dataset manifest sha256:{r['dataset_manifest_sha256'][:12]}"


def _names(root, sub, recursive=False) -> list:
    d = Path(root) / sub
    if not d.exists():
        return []
    files = d.rglob("*") if recursive else d.iterdir()
    return sorted(p.relative_to(d).as_posix() for p in files if p.is_file())


MEMOS_LISTED = 5


def _memo_lines(root) -> list:
    """The newest MEMOS_LISTED memos by number (memo10 after memo9), then a count of the older ones: the list grows with every memo and would push the file past MAX_LINES."""
    names = _names(root, "docs/memos")
    names.sort(key=lambda n: (int(m.group(1)) if (m := re.match(r"memo(\d+)", n)) else -1, n))
    older = names[:-MEMOS_LISTED]
    return [f"- {n}" for n in names[-MEMOS_LISTED:]] + ([f"({len(older)} older memos not listed)"] if older else [])


def roadmap_line(root) -> str:
    """One line for the roadmap: node count, frontier size and error count, computed from roadmap/nodes under root (tools/roadmap)."""
    tools = str(REPO / "tools")
    if tools not in sys.path:
        sys.path.insert(0, tools)
    import roadmap
    rm = roadmap.compute(root)
    nodes = "no nodes" if not rm.nodes and not rm.errors else f"{rm.node_count} nodes"
    return f"Roadmap: {nodes} | frontier {len(rm.frontier)} | errors {len(rm.errors)}"


def thread_line(root) -> str:
    """One line for the thread (tools/thread): records, work items, work items to rework (stale, drifted, unknown) and errors. Work statuses are
    only derived when the thread has no errors, so rework reads 0 beside a non-zero error count."""
    root = Path(root)
    if not (root / "thread").is_dir():
        return "Thread: no thread/"
    tools = str(REPO / "tools")
    if tools not in sys.path:
        sys.path.insert(0, tools)
    from thread import build
    b = build.build_root(root)
    work = sum(1 for r in b.recs.values() if r["kind"] == "work_item")
    rework = sum(1 for w in b.work.values() if w["status"] in ("stale", "drifted", "unknown"))
    return f"Thread: {len(b.recs)} records | {work} work items | rework {rework} | errors {len(b.errors)}"


def generate(root=None, run=True, runner=None) -> str:
    root = Path(root or REPO)
    head = _git(root, "rev-parse", "HEAD").strip()
    branch = _git(root, "rev-parse", "--abbrev-ref", "HEAD").strip()
    dirty, diff = tree_state(root)
    meta_path = root / "params" / "snapshot.meta.json"
    meta = json.loads(meta_path.read_text(encoding="utf-8")) if meta_path.exists() else {}
    snap, model = meta.get("snapshot_sha256", "missing")[:12], meta.get("model_sha256", "missing")[:12]
    results = (runner or default_runner)(root) if run else None
    if results:
        t = results["tests"]
        cached = t.get("cached", 0)  # passed on byte-identical inputs and not run again: counted as passed, and the section says how many
        tests_short = f"{t['passed'] + cached}/{t['passed'] + cached + t['failed'] + t['skipped']}"
    else:
        tests_short = "not run"
    paths = briefs(root)
    bh = {t: brief_hash(root, t) for t in paths}
    out = [f"<!-- {GENERATED.format(snap=snap)} -->", "",
           f"STATE: base {head[:12]} | brief {', '.join(f'{t} sha256:{h}' for t, h in bh.items())} | snapshot sha256:{snap} | tests {tests_short} | dirty {'yes' if dirty else 'no'}", "",
           "# State", "",
           f"Base commit: {head}", f"Branch: {branch}", f"Tree dirty: {'yes' if dirty else 'no'}",
           f"Diff hash (git diff HEAD, {STATE_FILE} excluded): {diff or 'none'}",
           *[l for t, p in paths.items() for l in (f"Brief ({t}): {p}", f"Brief sha256 ({t}, line endings normalised to LF): {bh[t]}")],
           f"Snapshot sha256: {snap}", f"Model sha256: {model}", roadmap_line(root), thread_line(root), "", "## Tests", ""]
    if results:
        note = f" ({cached} not run again: inputs unchanged since they last passed)" if cached else ""
        out.append(f"passed {t['passed'] + cached}{note}, failed {t['failed']}, skipped {t['skipped']}")
        if t.get("reused"):
            out.append(f"reported from the last full run, not run again: the tree is unchanged since (tree key {t['reused']}; "
                       f"{' and '.join(testkit.NEUTRAL)} are not part of the key)")
    else:
        out.append("not run (--no-run)")
    out += ["", "## Checks", ""]
    out += [f"- {i} | {tier} | {st}" for i, tier, st in sorted(results["checks"])] if results else ["not run (--no-run)"]
    out += ["", "## Waivers", ""]
    out += [f"- {c} | confirmed {'true' if conf else 'false'} | review by {rb}" for c, conf, rb in sorted(_waivers(root))] or ["none"]
    out += ["", "## Known failing (xfail)", ""] + (_xfails(root) or ["none"])
    out += ["", "## Latest run per scenario", ""] + [f"- {r}" for r in _latest_runs(root)] + [
        "", "## Latest gait record", "", _latest_gait(root), "", "## docs/memos", ""] + _memo_lines(root) + [
        "", "## docs/briefs", ""] + [f"- {n}" for n in _names(root, "docs/briefs", recursive=True)]
    tracked = [f for f in _git(root, "ls-files").splitlines() if f != STATE_FILE]
    out += ["", f"Tracked files: {len(tracked)} ({STATE_FILE} not counted)", ""]
    if len(out) > MAX_LINES:
        out = out[:MAX_LINES - 1] + [f"(truncated at {MAX_LINES} lines)"]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="fy state", description="Write docs/STATE.md: the exact state of this copy of the repo.")
    how = ap.add_mutually_exclusive_group()
    how.add_argument("--no-run", action="store_true", help="record the tests and checks as not run")
    how.add_argument("--rerun", action="store_true", help="run the whole suite even when the tree is unchanged since the last full run, "
                                                           "including the tests skipped on unchanged inputs")
    ns = ap.parse_args(sys.argv[1:] if argv is None else argv)  # --help or an unknown argument exits here, before anything runs
    try:
        text = generate(REPO, run=not ns.no_run, runner=(lambda root: default_runner(root, rerun=True)) if ns.rerun else None)
    except BriefLinesError as e:
        print(f"fy state: {e}", file=sys.stderr)
        return 1
    with open(REPO / STATE_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(text.splitlines()[2])
    return 0


if __name__ == "__main__":
    sys.exit(main())
