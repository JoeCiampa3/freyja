"""
Roadmap generated files: roadmap/state.json (roadmap-state/3) and roadmap/STATUS.md. Deterministic: sorted keys and ids, repo-relative
paths, LF line endings, no timestamps. Nothing is written when the graph has errors.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from .derive import LIVE_ORDER, Roadmap, compute
from .evaluate import referenced_files, safe_path
from .tags import TAGS_FILE

TOOL = "tools/roadmap"
STATE_JSON = "roadmap/state.json"
STATUS_MD = "roadmap/STATUS.md"
MERMAID_CAP = 40  # a flowchart larger than this is unreadable; above it the diagram is omitted and STATUS.md says so
GLYPH = {"done": "[x]", "blocked": "[#]", "active": "[>]", "ready": "[ ]", "expandable": "[+]", "in_progress": "[~]",
         "not_started": "[.]", "superseded": "[-]", "unknown": "[?]", "stale": "[!]"}


def inputs_hash(root, rm: Roadmap) -> str:
    """First 12 hex of a sha256 over the node files and every file a done_when reads, by path and content (staleness is a hash mismatch)."""
    if getattr(rm, "_inputs_hash", None):
        return rm._inputs_hash  # one Roadmap is one reading of the files; hash them once
    h = hashlib.sha256()
    paths = {n.path for n in rm.nodes.values()} | {TAGS_FILE}
    for n in rm.nodes.values():
        paths.update(referenced_files(n))
    for rel in sorted(paths):
        p = safe_path(root, rel)
        h.update(rel.encode("utf-8") + b"\0")
        if p is not None and p.is_file():
            h.update(p.read_bytes().replace(b"\r\n", b"\n"))
        else:
            h.update(b"<missing>")
        h.update(b"\0")
    return h.hexdigest()[:12]


def banner(root, rm: Roadmap) -> str:
    return (f"GENERATED by {TOOL} from roadmap/nodes and the records its done_when criteria read "
            f"(inputs sha256:{inputs_hash(root, rm)}). Do not edit; change the inputs and rebuild.")


def state_dict(rm: Roadmap, banner_text: str | None = None) -> dict:
    nodes = {}
    for i in sorted(rm.nodes):
        n, st = rm.nodes[i], rm.states[i]
        nodes[i] = {
            "title": n.title, "path": n.path, "kind": st.kind, "status": st.status, "reason": st.reason, "parent": n.parent,
            "children": rm.children(i), "blocked_by": sorted(n.blocked_by), "effective_blockers": rm.effective_blockers(i),
            "uncleared_blockers": rm.uncleared(i), "dependents": rm.dependents(i), "estimate_days": n.estimate_days, "tags": list(n.tags), "short": n.short,
            "active": n.active, "signed_off": n.signed_off, "superseded_by": n.superseded_by, "done_when": n.done_when,
            "evaluation": st.evaluation.to_dict() if st.evaluation else None}
    root = rm.root
    return {"_generated": banner_text if banner_text is not None else banner(root, rm), "generated_by": TOOL, "inputs": ["roadmap/nodes/*.md", TAGS_FILE], "schema": "roadmap-state/3",
            "node_count": rm.node_count, "superseded_count": rm.superseded_count, "counts": dict(sorted(rm.counts.items())),
            "frontier": list(rm.frontier), "errors": [e.to_dict() for e in rm.errors], "warnings": [w.to_dict() for w in rm.warnings],
            "tag_vocabulary": {ns: [{"value": value, "colour": colour} for value, colour in values.items()] for ns, values in sorted(rm.vocabulary.items())}, "nodes": nodes}  # values stay in file order: lists, because the file is written with sorted keys


def state_json_text(rm: Roadmap) -> str:
    return json.dumps(state_dict(rm), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def diagram_nodes(rm: Roadmap) -> list:
    """The frontier plus one hop of blockers and dependents, sorted."""
    ids = set(rm.frontier)
    for f in rm.frontier:
        ids.update(b for b in rm.effective_blockers(f) if b in rm.nodes and not rm.nodes[b].superseded)
        ids.update(rm.dependents(f))
    return sorted(ids)


def _mid(i: str) -> str:
    return "n_" + i.replace(".", "_").replace("-", "_")


def mermaid(rm: Roadmap, ids: list) -> list:
    inset = set(ids)
    lines = ["```mermaid", "flowchart LR"]
    for i in ids:
        label = f"{GLYPH[rm.status(i)]} {i}<br/>{rm.status(i)}".replace('"', "'")
        lines.append(f'    {_mid(i)}["{label}"]')
    edges = set()
    for d in ids:
        for b in rm.effective_blockers(d):
            if b in inset:
                edges.add((b, d))
    for b, d in sorted(edges):
        lines.append(f"    {_mid(b)} --> {_mid(d)}")
    lines.append("```")
    return lines


def _issue_lines(items) -> list:
    return [f"- `{x.code}`: {x.message}" for x in items] or ["none"]


def status_md_text(rm: Roadmap) -> str:
    out = [f"<!-- {banner(rm.root, rm)} -->", "", "# Roadmap status", ""]
    if not rm.nodes:
        out += ["no nodes", ""]
    out += ["## Counts", ""]
    out += [f"- {s}: {rm.counts[s]}" for s in LIVE_ORDER if s in rm.counts] or ["none"]
    out += [f"- superseded (not counted): {rm.superseded_count}", f"- nodes: {rm.node_count}", "", "## Problems", ""]
    out += ["Errors:", ""] + _issue_lines(rm.errors) + ["", "Warnings:", ""] + _issue_lines(rm.warnings)
    out += ["", "## Frontier", ""]
    for i in rm.frontier:
        n, st = rm.nodes[i], rm.states[i]
        crit = _criterion_text(n.done_when) if st.kind == "leaf" else "stub, not yet decomposed"
        est = f", {n.estimate_days:g} d" if n.estimate_days is not None else ""
        out.append(f"- `{i}` {n.title} ({crit}{est})")
    out += [] if rm.frontier else ["none"]
    out += ["", "## Active", ""]
    active = [i for i in sorted(rm.nodes) if rm.states[i].status == "active"]
    for i in active:
        n = rm.nodes[i]
        out.append(f"- `{i}` {n.title} ({_criterion_text(n.done_when)})")
    out += [] if active else ["none"]
    out += ["", "## Graph", ""]
    ids = diagram_nodes(rm)
    if not ids:
        out.append("No frontier, so no diagram.")
    elif len(ids) > MERMAID_CAP:
        out.append(f"Diagram omitted: the frontier plus one hop of blockers and dependents is {len(ids)} nodes, more than {MERMAID_CAP}.")
    else:
        out += mermaid(rm, ids)
    return "\n".join(out) + "\n"


def _criterion_text(dw) -> str:
    if not dw:
        return "no criterion"
    t = dw["type"]
    detail = {"artifact": dw.get("path"), "decision": dw.get("record"), "check": dw.get("check"),
              "metric": f"{dw.get('record')} {dw.get('pointer')} {dw.get('op')} {dw.get('value')}"}.get(t, "")
    return f"{t}: {detail}" if detail else t


def criterion_text(dw) -> str:
    return _criterion_text(dw)


def build(root, out_dir=None):
    """Validate and write roadmap/state.json and roadmap/STATUS.md under `root`. Returns the Roadmap, or None (writing nothing) on errors."""
    rm = compute(root)
    if rm.errors:
        return None
    d = Path(out_dir or root) / "roadmap"
    d.mkdir(parents=True, exist_ok=True)
    for name, text in (("state.json", state_json_text(rm)), ("STATUS.md", status_md_text(rm))):
        with open(d / name, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return rm
