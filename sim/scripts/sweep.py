"""
Posture sweep (Stage 1c T5): the static standing torques over a grid of pose parameters.

    python sim/scripts/sweep.py <spec>          (or: fy sweep <spec>)

A spec (sim/scenarios/sweeps/<name>.yaml) names a base scenario (its pose block), a grid of up to three pose parameters
(start, stop, n) and two constraints, min_support_margin_m (default 0.02) and min_limit_margin_deg (default 2.0). Every grid
point is a pose solve (leanpose) and a static solve (statics): no controller, no gains, no run directory. The result is
sim/sweeps/<id>/sweep.json (schema docs/schemas/sweep-summary-1.schema.json) and a generated SWEEP.md, both deterministic.

A sum of squared torques is unnormalised, and a minimum over the grid is a property of the model, not a recommended posture.
"""
from __future__ import annotations

import argparse
import datetime as dt
import itertools
import json
import re
import sys
import time
from dataclasses import dataclass
from pathlib import Path

import numpy as np

import leanpose
import runrecord
import simrun
import statics
from simrun import StaleModelError  # noqa: F401  (re-exported)

REPO = Path(__file__).resolve().parents[2]
SPECS_DIR = REPO / "sim" / "scenarios" / "sweeps"
SWEEPS_DIR = REPO / "sim" / "sweeps"
SCHEMA_FILE = REPO / "docs" / "schemas" / "sweep-summary-1.schema.json"
MAX_POINTS = 2000  # the brief's cap
MAX_PARAMS = 3
POINT_ROWS_MAX = 250  # the per-point table is listed in full up to this many points, so SWEEP.md stays under the line cap
EXTREMES_SHOWN = 15  # lowest and highest sum-of-squares points listed when the grid is larger
MAX_LINES = 399
DEFAULT_CONSTRAINTS = {"min_support_margin_m": 0.02, "min_limit_margin_deg": 2.0}
CHAIN = (("hip flexion", "hip_fe_right"), ("knee", "knee_right"), ("ankle", "ankle_pdflex_right"),
         ("lumbosacral", "lsj_fe"), ("thoracic", "tj_fe"), ("cervical", "cj_fe"))
GENERATED = "GENERATED by sim/scripts/sweep.py from the sweep spec and the model (snapshot sha256:{snap}). Do not edit; rerun `fy sweep {name}`."


class SweepError(ValueError):
    """A bad spec or a sweep that cannot be run."""


@dataclass
class SweepResult:
    record: dict
    path: Path
    ms_per_point: float


# ------------------------------------------------------------------------------ spec and grid

def load_spec(name: str, specs_dir=None) -> dict:
    import yaml
    path = Path(specs_dir or SPECS_DIR) / f"{name}.yaml"
    if not path.is_file():
        raise SweepError(f"no sweep spec {path}")
    spec = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if spec.get("name") != name:
        raise SweepError(f"{path.name}: name is '{spec.get('name')}', it must be '{name}'")
    return spec


def check_spec(spec: dict) -> dict:
    """-> the spec with defaults filled in, or SweepError."""
    for key in ("name", "base", "grid"):
        if key not in spec:
            raise SweepError(f"sweep spec is missing '{key}'")
    grid = spec["grid"]
    if not grid or len(grid) > MAX_PARAMS:
        raise SweepError(f"a sweep needs between 1 and {MAX_PARAMS} grid parameters, got {len(grid or {})}")
    known = set(leanpose.POSE_JOINTS) | {"com_x_rel_ankle_m"}
    for key, axis in grid.items():
        if key not in known:
            raise SweepError(f"'{key}' is not a pose parameter (one of {sorted(known)})")
        if not all(k in axis for k in ("start", "stop", "n")) or int(axis["n"]) < 1:
            raise SweepError(f"grid axis '{key}' needs start, stop and n >= 1")
    constraints = {**DEFAULT_CONSTRAINTS, **(spec.get("constraints") or {})}
    unknown = set(constraints) - set(DEFAULT_CONSTRAINTS)
    if unknown:
        raise SweepError(f"unknown constraint(s): {sorted(unknown)}")
    return {"name": spec["name"], "base": spec["base"],
            "grid": {k: {"start": float(v["start"]), "stop": float(v["stop"]), "n": int(v["n"])} for k, v in grid.items()},
            "constraints": {k: float(v) for k, v in constraints.items()}}


def grid_points(grid: dict) -> list:
    """Cartesian product, the last parameter varying fastest. n = 1 sits at start."""
    axes = []
    for key, a in grid.items():
        n = int(a["n"])
        values = [float(a["start"])] if n == 1 else [float(a["start"]) + i * (float(a["stop"]) - float(a["start"])) / (n - 1) for i in range(n)]
        axes.append([(key, round(v, 12)) for v in values])
    return [dict(combo) for combo in itertools.product(*axes)]


# ------------------------------------------------------------------------------ evaluation

def evaluate_point(model, base_pose: dict, params: dict, feet: dict, constraints: dict) -> dict:
    import mujoco
    point = {"params": dict(params), "feasible": False, "reasons": [], "support_margin_m": None, "limit_margin_min_deg": None,
             "limit_joint": None, "torques": None, "sum_squares_nm2": None}
    try:
        lean = leanpose.solve_pose(model, {**base_pose, **params}, feet)
    except leanpose.LeanError as e:
        point["reasons"] = [str(e)]
        return point
    data = mujoco.MjData(model)
    data.qpos[:] = lean.qpos
    mujoco.mj_forward(model, data)
    result = statics.solve_static(model, data, feet=tuple(sorted(feet, reverse=True)))
    reasons = list(result.reasons)
    margin, lim = result.support_margin_m, result.limit_margin_deg
    if result.feasible and margin < constraints["min_support_margin_m"]:
        reasons.append(f"support margin {margin * 1000:.1f} mm is below the {constraints['min_support_margin_m'] * 1000:.1f} mm constraint")
    if result.feasible and lim is not None and lim < constraints["min_limit_margin_deg"]:
        reasons.append(f"{result.limit_joint} is {lim:.2f} deg from a limit, below the {constraints['min_limit_margin_deg']:.1f} deg constraint")
    point.update(feasible=not reasons, reasons=reasons, support_margin_m=float(margin) if np.isfinite(margin) else None,
                 limit_margin_min_deg=lim, limit_joint=result.limit_joint, torques=dict(sorted(result.torque.items())),
                 sum_squares_nm2=float(sum(v * v for v in result.torque.values())))
    return point


def _ranges(points) -> dict:
    ok = [p for p in points if p["feasible"]]
    if not ok:
        return {}
    out = {}
    for joint in sorted(ok[0]["torques"]):
        vals = [p["torques"][joint] for p in ok]
        out[joint] = {"min": min(vals), "max": max(vals), "spread": max(vals) - min(vals)}
    return out


# ------------------------------------------------------------------------------ record and validation

def load_schema():
    return json.loads(SCHEMA_FILE.read_text(encoding="utf-8"))


def validate(record) -> None:
    import jsonschema
    errors = sorted(jsonschema.Draft202012Validator(load_schema()).iter_errors(record), key=lambda e: list(map(str, e.path)))
    if errors:
        raise SweepError("; ".join(f"{'.'.join(map(str, e.path)) or '<record>'}: {e.message}" for e in errors[:5]))


def run_sweep(spec: dict, *, model_path=None, snapshot_path=None, meta_path=None, sweeps_dir=None, base_scenario=None,
              scenarios_dir=None, now=None, repo=None) -> SweepResult:
    import mujoco
    spec = check_spec(spec)
    points_grid = grid_points(spec["grid"])
    if len(points_grid) > MAX_POINTS:
        raise SweepError(f"the grid has {len(points_grid)} points; the limit is {MAX_POINTS}")
    model_path, snapshot_path = Path(model_path or simrun.MODEL_FILE), Path(snapshot_path or simrun.SNAPSHOT_FILE)
    sweeps_dir = Path(sweeps_dir or SWEEPS_DIR)
    sweep_id = f"sweep.{(now or dt.datetime.now()):%Y%m%d-%H%M}-{spec['name']}"
    if not runrecord.NAME_RE.match(spec["name"]):
        raise SweepError(f"spec name '{spec['name']}' must be lowercase letters, digits, underscore or hyphen")
    model_sha, snapshot_sha = simrun.verify_inputs(model_path, snapshot_path, meta_path or simrun.META_FILE)
    out_dir = sweeps_dir / sweep_id.removeprefix("sweep.")
    if out_dir.exists():
        raise SweepError(f"{sweep_id} already exists; an id has minute resolution, so wait for the next minute")
    base = base_scenario if base_scenario is not None else simrun.load_scenario(spec["base"], scenarios_dir)
    base_pose = dict(base.get("pose") or {})
    if not base_pose:
        raise SweepError(f"base scenario {spec['base']} has no pose block")

    model = mujoco.MjModel.from_xml_path(str(model_path))
    feet = {}
    for side in ("right", "left"):
        if simrun._body_id(model, f"foot_{side}") is not None and mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, f"ankle_pdflex_{side}") >= 0:
            feet[f"foot_{side}"] = f"ankle_pdflex_{side}"
    if not feet:
        raise SweepError("the model needs foot_right/foot_left bodies with ankle_pdflex joints")

    started = time.perf_counter()
    points = [evaluate_point(model, base_pose, p, feet, spec["constraints"]) for p in points_grid]
    ms_per_point = (time.perf_counter() - started) * 1000.0 / len(points)

    feasible = [p for p in points if p["feasible"]]
    best = min(feasible, key=lambda p: (p["sum_squares_nm2"], json.dumps(p["params"], sort_keys=True)), default=None)
    record = {
        "schema": "sweep-summary/1", "sweep_id": sweep_id, **runrecord.git_state(repo),
        "snapshot_sha256": snapshot_sha, "model_sha256": model_sha, "env": runrecord.env_versions(),
        "spec": spec, "base_pose": base_pose, "points": points, "ranges": _ranges(points),
        "minimum": None if best is None else {"params": best["params"], "sum_squares_nm2": best["sum_squares_nm2"]},
        "unbounded_joints": sorted(h["name"] for h in simrun._hinges(model) if h["limit"] is None),
        "counts": {"points": len(points), "feasible": len(feasible)},
    }
    validate(record)
    out_dir.mkdir(parents=True)
    with open(out_dir / "sweep.json", "w", encoding="utf-8", newline="\n") as f:
        f.write(runrecord.dumps(record))
    with open(out_dir / "SWEEP.md", "w", encoding="utf-8", newline="\n") as f:
        f.write(render_md(record))
    return SweepResult(record, out_dir / "sweep.json", ms_per_point)


# ------------------------------------------------------------------------------ SWEEP.md

def _g(x, nd=2) -> str:
    return "-" if x is None else f"{x:.{nd}f}"


def _row(record, p) -> str:
    keys = list(record["spec"]["grid"])
    cells = [f"{p['params'][k]:g}" for k in keys]
    cells.append("yes" if p["feasible"] else "no")
    cells.append("; ".join(p["reasons"]) or "-")
    cells.append(_g(None if p["support_margin_m"] is None else p["support_margin_m"] * 1000, 1))
    t = p["torques"]
    for _, joint in CHAIN:
        cells.append(_g(None if t is None or joint not in t else t[joint]))
    cells.append(_g(p["sum_squares_nm2"], 1))
    return "| " + " | ".join(cells) + " |"


def _table_head(record) -> list:
    cols = list(record["spec"]["grid"]) + ["feasible", "reason", "margin mm"] + [f"{label} Nm" for label, _ in CHAIN] + ["sum sq Nm2"]
    return ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]


def _group_reason(reason: str) -> str:
    """The reason with its numbers replaced by #, so equal causes group together."""
    return re.sub(r"[-+]?\d+(\.\d+)?", "#", reason)


def render_md(record: dict) -> str:
    spec, counts = record["spec"], record["counts"]
    pts = record["points"]
    lines = [f"<!-- {GENERATED.format(snap=record['snapshot_sha256'][:12], name=spec['name'])} -->", "", f"# Posture sweep: {spec['name']}", "",
             f"{record['sweep_id']}, base scenario {spec['base']}, commit {record['git_commit'][:7]}{'+dirty' if record['git_dirty'] else ''}, "
             f"snapshot {record['snapshot_sha256'][:12]}, model {record['model_sha256'][:12]}.",
             "Torques are static joint torques about the model's own hinge axes (the decoupled hip architecture), not actuator torque, "
             "from sim/scripts/statics.py: no controller and no gains enter them.",
             "The sum of squared torques is unnormalised: it weights every joint equally, whatever its size or role. A minimum over the grid is "
             "a property of the model, not a recommended posture. The grid ranges are placeholders unless the spec cites a source.", "",
             "## Grid", "", "| parameter | start | stop | n |", "|---|---|---|---|"]
    for k, a in spec["grid"].items():
        lines.append(f"| {k} | {a['start']:g} | {a['stop']:g} | {a['n']} |")
    c = spec["constraints"]
    lines += ["", f"Base pose {json.dumps(record['base_pose'], sort_keys=True)}. Constraints: support margin at least {c['min_support_margin_m'] * 1000:g} mm, "
                  f"limit margin at least {c['min_limit_margin_deg']:g} deg. Feasible points: {counts['feasible']} of {counts['points']}."]
    if record["minimum"]:
        lines.append(f"Lowest sum of squares among feasible points: {record['minimum']['sum_squares_nm2']:.1f} N2 m2 at {json.dumps(record['minimum']['params'], sort_keys=True)}.")
    else:
        lines.append("No point is feasible.")

    # the corners of the grid
    keys = list(spec["grid"])
    ends = [sorted({0, a["n"] - 1}) for a in spec["grid"].values()]
    values = [grid_points({k: spec["grid"][k]}) for k in keys]
    index = {json.dumps(p["params"], sort_keys=True): p for p in pts}
    lines += ["", "## Corners of the grid", ""] + _table_head(record)
    for combo in itertools.product(*ends):
        params = {k: values[i][combo[i]][k] for i, k in enumerate(keys)}
        p = index.get(json.dumps(params, sort_keys=True))
        if p is not None:
            lines.append(_row(record, p))

    lines += ["", "## Torque range per joint across the feasible points", ""]
    if record["ranges"]:
        lines += ["| joint | min Nm | max Nm | spread Nm | bounds |", "|---|---|---|---|---|"]
        unb = set(record["unbounded_joints"])
        for joint, r in record["ranges"].items():
            lines.append(f"| {joint} | {r['min']:.2f} | {r['max']:.2f} | {r['spread']:.2f} | {'unbounded' if joint in unb else 'limited'} |")
        if unb:
            lines += ["", "Joints with no limits are unbounded in the model, so the sweep ranges are the only bounds on them: " + ", ".join(sorted(unb)) + "."]
    else:
        lines.append("No feasible point, so no ranges.")

    lines += ["", "## Points", ""]
    if len(pts) <= POINT_ROWS_MAX:
        lines += _table_head(record) + [_row(record, p) for p in pts]
    else:
        lines.append(f"{len(pts)} points: the full list is in sweep.json. Infeasible points by reason:")
        groups = {}
        for p in pts:
            if not p["feasible"]:
                for r in p["reasons"]:
                    groups[_group_reason(r)] = groups.get(_group_reason(r), 0) + 1
        lines += [f"- {n} x {r}" for r, n in sorted(groups.items())] or ["- none"]
        ok = sorted((p for p in pts if p["feasible"]), key=lambda p: (p["sum_squares_nm2"], json.dumps(p["params"], sort_keys=True)))
        if ok:
            lines += ["", f"The {min(EXTREMES_SHOWN, len(ok))} feasible points with the lowest sum of squares:", ""] + _table_head(record)
            lines += [_row(record, p) for p in ok[:EXTREMES_SHOWN]]
            lines += ["", f"The {min(EXTREMES_SHOWN, len(ok))} with the highest:", ""] + _table_head(record)
            lines += [_row(record, p) for p in ok[::-1][:EXTREMES_SHOWN]]
    if len(lines) > MAX_LINES:
        lines = lines[:MAX_LINES - 1] + [f"(truncated at {MAX_LINES} lines)"]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------ command line

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="fy sweep", description="Sweep pose parameters and record the static standing torques.")
    ap.add_argument("spec", help="name of a file in sim/scenarios/sweeps/ (without .yaml)")
    ap.add_argument("--specs-dir", help=argparse.SUPPRESS)
    ap.add_argument("--sweeps-dir", help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    try:
        result = run_sweep(load_spec(args.spec, args.specs_dir), sweeps_dir=args.sweeps_dir)
    except (SweepError, simrun.ScenarioError, StaleModelError, runrecord.RecordError) as e:
        print(f"sweep: {e}", file=sys.stderr)
        return 2
    rec = result.record
    print(f"{rec['sweep_id']}: {rec['counts']['feasible']} of {rec['counts']['points']} points feasible, {result.ms_per_point:.1f} ms per point")
    print(f"  {result.path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
