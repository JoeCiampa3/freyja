GAIT_EXTRACT_FILE = REPO / "sim" / "benchmarks" / "gait_extract.json"


def load_gait_extract(path=None):
    """The tracked gait extract (gait-extract/1), or None when there is none. It is written by `fy gait`; the envelope never reads a gait.json."""
    path = Path(path or GAIT_EXTRACT_FILE)
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def envelope(summaries, current_model_sha=None, gait=None) -> str:
    lines = [f"<!-- {GENERATED_ENVELOPE} -->", "", "# Load envelope", ""]
    groups = _latest_by_scenario(summaries)
    if not groups and gait is None:
        return _cap(lines + ["No runs recorded yet."])
    included, excluded = {}, []
    for name in sorted(groups):
        s = groups[name][-1]
        if current_model_sha is not None and s["model_sha256"] != current_model_sha:
            excluded.append(f"{s['run_id']} ({name}): stale, recorded for another model")
        elif s["scenario"]["params"].get("envelope", True) is False:
            excluded.append(f"{s['run_id']} ({name}): verification only (envelope: false), so it never drives a row")
        elif s["outcome"] != "completed":
            excluded.append(f"{s['run_id']} ({name}): {s['outcome']}, so its numbers do not count")
        else:
            included[name] = s
    if gait is not None and current_model_sha is not None and gait["model_sha256"] != current_model_sha:
        excluded.append(f"{gait['gait_id']} ({gait['spec']['name']}): stale, recorded for another model")
        gait = None
    classes = [f"{n} ({included[n]['run_id']})" for n in sorted(included)] + ([f"{gait['spec']['name']} ({gait['gait_id']}, gait rows below)"] if gait else [])
    lines += [
        "Worst case per joint across the latest run of every scenario, with the run that drives it. Joint torque is about the model's own "
        "hinge axes (the decoupled hip architecture), not actuator torque.",
        "",
        "Scenario classes included: " + (", ".join(classes) or "none") + ".",
        "Not yet included: " + ", ".join(NOT_INCLUDED_GAIT if gait else NOT_INCLUDED) + " (they need reference kinematics with citable provenance; running is out of scope)." if gait
        else "Not yet included: " + ", ".join(NOT_INCLUDED) + " (they need reference kinematics with citable provenance, Stage 2).",
        "This is not a complete sizing basis: do not size an actuator from it.",
    ]
    if excluded:
        lines += ["Excluded latest runs: " + "; ".join(excluded) + "."]
    lines.append("")

    best, rom, limits, no_rom = {}, {}, {}, set()
    for name in sorted(included):
        s = included[name]
        no_rom |= set(s.get("skipped", {}))
        for jn, j in s["joints"].items():
            if j["rom_limit_deg"] is None:
                no_rom.add(jn)
            else:
                limits.setdefault(jn, j["rom_limit_deg"])
            lo, hi = j["rom_used_deg"]
            cur = rom.setdefault(jn, [lo, hi])
            cur[0], cur[1] = min(cur[0], lo), max(cur[1], hi)
            for key in JOINT_METRICS:
                cand = (j[key], s["run_id"])
                have = best.setdefault(jn, {}).get(key)
                # larger value wins; on a tie the smaller run id
                if have is None or cand[0] > have[0] or (cand[0] == have[0] and cand[1] < have[1]):
                    best[jn][key] = cand
    names = sorted(set(best) | no_rom)
    lines += ["| joint | peak torque Nm | driving run | peak speed rad/s | driving run | peak power W | driving run | ROM used deg | limit deg |",
              "|" + "---|" * 9]
    for jn in names:
        if jn not in best:
            lines.append(f"| {jn} | no data | - | no data | - | no data | - | - | unlimited |")
            continue
        b = best[jn]
        lines.append(f"| {jn} | {b['torque_peak_nm'][0]:.2f} | {b['torque_peak_nm'][1]} | {b['speed_peak_rad_s'][0]:.3f} | {b['speed_peak_rad_s'][1]} | "
                     f"{b['power_peak_w'][0]:.2f} | {b['power_peak_w'][1]} | {_rom(rom[jn])} | {_rom(limits.get(jn)) if jn in limits else 'unlimited'} |")
    lines.append("")
    if no_rom:
        lines.append("Joints with no ROM data (unlimited, so never swept; each row reflects the static standing solve only, or no data): "
                     + ", ".join(sorted(no_rom)) + ".")
    else:
        lines.append("Joints with no ROM data: none.")
    if gait is not None:
        lines += gait_section(gait)
    return _cap(lines)


# ------------------------------------------------------------------------------ command line

def _find(summaries, ident):
    wanted = ident if ident.startswith("run.") else f"run.{ident}"
    for s in summaries:
        if s["run_id"] == wanted:
            return s
    raise KeyError(f"no run {ident}")


def _current_model_sha(meta_path):
    try:
        return json.loads(Path(meta_path).read_text(encoding="utf-8")).get("model_sha256")
    except (OSError, ValueError):
        return None


def main(argv=None) -> int:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--runs-dir", help=argparse.SUPPRESS)
    common.add_argument("--meta", help=argparse.SUPPRESS)
    common.add_argument("--repo", help=argparse.SUPPRESS)
    common.add_argument("--extract", help=argparse.SUPPRESS)
    ap = argparse.ArgumentParser(prog="fy runs", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="command", required=True)
    p = sub.add_parser("list", parents=[common], help="list runs")
    p.add_argument("--scenario")
    sub.add_parser("show", parents=[common], help="show one run").add_argument("run")
    p = sub.add_parser("compare", parents=[common], help="compare two runs")
    p.add_argument("a")
    p.add_argument("b")
    sub.add_parser("digest", parents=[common], help="write sim/runs/DIGEST.md")
    sub.add_parser("envelope", parents=[common], help="write sim/runs/ENVELOPE.md")
    args = ap.parse_args(argv)

    runs_dir = Path(args.runs_dir or runrecord.RUNS_DIR)
    summaries = runrecord.load_summaries(runs_dir)
    try:
        if args.command == "list":
            sys.stdout.write(list_runs(summaries, args.scenario))
        elif args.command == "show":
            sys.stdout.write(show(_find(summaries, args.run)))
        elif args.command == "compare":
            sys.stdout.write(compare(_find(summaries, args.a), _find(summaries, args.b), repo=args.repo))
        else:
            sha = _current_model_sha(args.meta or META_FILE)
            text, name = (digest(summaries, sha), "DIGEST.md") if args.command == "digest" else (envelope(summaries, sha, gait=load_gait_extract(args.extract)), "ENVELOPE.md")
            path = runs_dir / name
            runs_dir.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print(f"wrote {path} ({len(text.splitlines())} lines)")
    except KeyError as e:
        print(f"runs: {e.args[0]}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
