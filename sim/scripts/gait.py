"""
Stage 2 T5: the gait batch runner. For every subject-stride of the Camargo et al. treadmill data at the speeds in the spec it
retargets the kinematics onto Freyja (retarget.py) and computes joint loads three ways on the same motion:

  B  Freyja's own dynamics: the root rows of inverse dynamics give the net ground wrench, the CoP is solved from moment balance
     (dynamics.solve_frame). `B` is the nominal double-support split; `B_bound` keeps the worst case over the feasible splits.
  A  the measured ground force and CoP scaled to Freyja (gaitloads), with the native force (`A_native`) and with the force
     filtered like the kinematics (`A_filtered`). The root rows generally do not close.
  H  Freyja's own total force applied at the measured CoP, shared as the measured force is. The force rows close.

    python sim/scripts/gait.py <spec>          (or: fy gait <spec>)

Writes sim/gait/<id>/gait.json (schema docs/schemas/gait-summary-1.schema.json, untracked) a generated GAIT.md (tracked: header, band table of every
speed, sensitivity) and one GAIT-<speed>.md per speed (tracked), each under MAX_LINES.
Both are deterministic: no timestamps beyond the id, sorted keys, fixed rounding. No pass or fail on agreement yet.
"""
