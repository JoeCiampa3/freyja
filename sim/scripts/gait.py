REFERENCE_SUBSET = {"subjects": ["AB06"], "speeds_mps": [1.4], "stride_cap_per_subject": 3}
REFERENCE_TOL = 1e-6  # relative to the larger magnitude, floor 1e-9: the computation is deterministic, this only absorbs round-off


def reference_metrics(spec=None, *, methods=None, model_path=None, manifest_path=None, processed=None) -> dict:
    """Agreement with the dataset's moments (mean over the subset's strides) for each trunk mode, method and joint, keyed "mode/method", on
    REFERENCE_SUBSET with the walk_treadmill spec's rules. Pure function of the model, the processed data and the spec."""
    spec = dict(spec or load_spec("walk_treadmill"))
    spec.update(REFERENCE_SUBSET)
    methods = list(methods or spec["methods"])
    model_path = Path(model_path or simrun.MODEL_FILE)
    manifest = json.loads(Path(manifest_path or REPO / spec["dataset"]["manifest"]).read_text(encoding="utf-8"))
    out = {}
    for mode in trunk_modes(spec):
        tasks = _tasks(spec, manifest, model_path, Path(processed or REPO / spec["dataset"]["processed"]), methods,
                       float(spec["smoothing"]["cutoff_hz"]), float(spec["pelvis_pitch_offset_deg"]), spec["stride_cap_per_subject"], True, True, False, trunk=mode)
        rows = _run_tasks(tasks, 1)
        for m in rows[0]["agree"]:
            out[f"{mode}/{m}"] = {j: {k: float(np.mean([r["agree"][m][j][k] for r in rows])) for k in ("rms_pct_ptp", "peak_diff", "corr")}
                                  for j in rows[0]["agree"][m]}
    return out


def compare_reference(baseline: dict, current: dict, tol=REFERENCE_TOL) -> list:
    """Lines naming every metric that differs by more than tol (relative to the larger magnitude, floor 1e-9), or is missing."""
    diffs = []
    for m in sorted(set(baseline) | set(current)):
        for j in sorted(set(baseline.get(m, {})) | set(current.get(m, {}))):
            for k in sorted(set(baseline.get(m, {}).get(j, {})) | set(current.get(m, {}).get(j, {}))):
                a, b = baseline.get(m, {}).get(j, {}).get(k), current.get(m, {}).get(j, {}).get(k)
                if a is None or b is None:
                    diffs.append(f"{m}/{j}/{k}: missing in {'baseline' if a is None else 'current'}")
                elif abs(a - b) > tol * max(abs(a), abs(b), 1e-9 / tol):
                    diffs.append(f"{m}/{j}/{k}: baseline {a:.9g}, now {b:.9g}")
    return diffs


def band_table(record: dict) -> dict:
    """The band verdict of every method at every speed and trunk mode of a record: {speed: {mode: {method: verdict}}}."""
    return {sp: {mode: {m: v["all"] for m, v in d["band"].items()} for mode, d in by_mode.items()} for sp, by_mode in record["results"].items()}


def write_baseline(record: dict, path=None, *, model_path=None) -> Path:
    """sim/benchmarks/walk_reference.json. The full run's band verdicts for every method (the finding for those that miss), and for the
    methods that meet the band at every speed and trunk mode a reproducible subset (check.sim.walk_reference). B and H are baselined only
    if they meet the band; nothing is chosen or tuned here."""
    path = Path(path or BENCHMARK_FILE)
    spec = record["spec"]
    table = band_table(record)
    split = baseline_methods({(sp, mode): v for sp, by_mode in table.items() for mode, v in by_mode.items()})
    body = {
        "generated_by": "sim/scripts/gait.py --write-baseline", "inputs": ["sim/scenarios/gait/walk_treadmill.yaml", "data/camargo2021/manifest.json", "sim/models/freyja.xml"],
        "schema": "walk-reference/1", "snapshot_sha256": record["snapshot_sha256"], "model_sha256": record["model_sha256"],
        "spec_sha256": record["spec_sha256"], "git_commit": record["git_commit"], "git_dirty": record["git_dirty"], "gait_id": record["gait_id"],
        "dataset_manifest_sha256": record["dataset_manifest_sha256"],
        "band": {"corr_min": BAND_CORR, "rms_pct_ptp_max": BAND_RMS_PCT, "stems": list(BAND_STEMS)},
        "baselined_methods": split["baselined"], "not_baselined_methods": split["not_baselined"],
        "band_verdicts_full_run": table,
        "reproduction": {"subset": REFERENCE_SUBSET, "tolerance_rel": REFERENCE_TOL, "metrics": None},
    }
    body = _round(body)
    # the reproduction metrics stay at full precision: the check compares at 1e-6 relative, finer than the record's 6 decimals
    body["reproduction"]["metrics"] = reference_metrics(spec, methods=split["baselined"], model_path=model_path) if split["baselined"] else {}
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(runrecord.dumps(body))
    return path


# ------------------------------------------------------------------------------ GAIT.md

def _f(x, nd=1):
    return "-" if x is None else f"{x:.{nd}f}"


def _cell(s, nd=1):
    return f"{s['mean']:.{nd}f} / {s['p95']:.{nd}f} / {s['max']:.{nd}f}"


def _short(mode):
    return TRUNK_SHORT.get(mode, mode)


def _method_cols(modes, methods):
    """(label, method, mode) per column. A's leg rows do not depend on the trunk mode (tested), so A takes the first mode; B and H get one
    column per mode."""
    cols = []
    for m in ("B", "A_native", "A_filtered", "H"):
        if m not in methods:
            continue
        cols += [(m, m, modes[0])] if m.startswith("A") else [(f"{m} {_short(x)}", m, x) for x in modes]
    return cols


def _pooled(d, m, stem, key="all"):
    """Both limbs pooled: (corr, rms % of ptp) of method m for a joint stem, from the record's agreement table."""
    suf = "" if key == "all" else "_without_offset"
    a = [d["agreement"][m][f"{stem}_{s}"] for s in ("right", "left")]
    return float(np.mean([x["corr" + suf] for x in a])), float(np.mean([x["rms_pct_ptp" + suf] for x in a]))


def _in_model_order(names):
    """`names` in the order of the mapping's joints then EXTRA_JOINTS (Context.joints); a stored record has sorted keys."""
    order = list(yaml.safe_load(MAPPING_FILE.read_text(encoding="utf-8"))["joints"]) + list(EXTRA_JOINTS)
    return sorted(names, key=lambda j: order.index(j) if j in order else len(order))


def speed_tag(speed) -> str:
    """0.5 -> 0p5 (the file and load-case naming of the repo: `lc.walk-1p4`)."""
    return str(speed).replace(".", "p")


def speed_file_name(speed) -> str:
    return f"GAIT-{speed_tag(speed)}.md"


def _band_lines(rec: dict, modes: list) -> list:
    """## Band: A_filtered, A_native, B and H against the dataset's moments, every speed, both limbs pooled, the band stems, then the verdict per exclusion set."""
    methods = [m for m in METHODS_ALL if m in next(iter(next(iter(rec["results"].values()))[modes[0]]["joints"].values()))]
    cols = _method_cols(modes, methods)
    L = ["", "## Band: correlation / RMS % of the dataset's peak-to-peak, both limbs pooled, mean over strides", "",
         f"Band to meet: correlation >= {BAND_CORR} and RMS <= {BAND_RMS_PCT:.0f}% of the dataset's peak-to-peak, for each of {', '.join(BAND_STEMS)}. A row that misses is a finding, not a failure of the run.", "",
         "| m/s | stem | " + " | ".join(c[0] for c in cols) + " |", "|---|---|" + "---|" * len(cols)]
    for speed, by_mode in rec["results"].items():
        by_mode = {m: by_mode[m] for m in modes}
        d0 = by_mode[modes[0]]
        if not d0["agreement"]:
            continue
        for stem in BAND_STEMS:
            L.append(f"| {speed} | {stem} | " + " | ".join("{:.2f} / {:.0f}%".format(*_pooled(by_mode[x], m, stem)) for _, m, x in cols) + " |")
        ks = ("all", "without_offset") + (("without_pitch_flagged",) if d0.get("n_strides_without_pitch_flagged") is not None else ())
        L.append(f"| {speed} | meets ({' / '.join(k.replace('_', ' ') for k in ks)}) | " + " | ".join(
            " / ".join("yes" if by_mode[x]["band"][m][k]["meets"] else "no" for k in ks) for _, m, x in cols) + " |")
    return L


