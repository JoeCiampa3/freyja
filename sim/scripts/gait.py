def load_spec(name: str, specs_dir=None) -> dict:
    path = Path(specs_dir or SPECS_DIR) / f"{name}.yaml"
    if not path.exists():
        raise GaitError(f"no gait spec {path}")
    spec = yaml.safe_load(path.read_text(encoding="utf-8"))
    if spec.get("name") != name:
        raise GaitError(f"{path.name}: the name key must be '{name}'")
    return spec


def _canon(x) -> str:
    return json.dumps(x, sort_keys=True, default=str)


def _sha(x) -> str:
    return hashlib.sha256(_canon(x).encode()).hexdigest()


class Context:
    """Model, mapping and standing pose, built once per process."""

    def __init__(self, model_path, mapping_path=MAPPING_FILE):
        self.model = mujoco.MjModel.from_xml_path(str(model_path))
        self.mapping = yaml.safe_load(Path(mapping_path).read_text(encoding="utf-8"))
        self.stand = leanpose.solve_lean(self.model, 0.0, STANDING_FEET).qpos
        self.mass = float(self.model.body_mass.sum())
        self.weight = self.mass * abs(float(self.model.opt.gravity[2]))
        m = self.model
        self.hinge = {mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_JOINT, j): (int(m.jnt_qposadr[j]), int(m.jnt_dofadr[j]))
                      for j in range(m.njnt) if m.jnt_type[j] == mujoco.mjtJoint.mjJNT_HINGE}
        self.joints = list(self.mapping["joints"]) + list(EXTRA_JOINTS)
        hip = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, "hip_fe_right")
        self.hip_stop_deg = float(np.degrees(m.jnt_range[hip][0]))
        box = next(g for g in range(m.ngeom) if m.geom_type[g] == mujoco.mjtGeom.mjGEOM_BOX
                   and mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_BODY, int(m.geom_bodyid[g])) == "foot_right")
        self.mu = float(m.geom_friction[box][0])


_CTX = {}
_PROC = {}


def _ctx(model_path) -> Context:
    if model_path not in _CTX:
        _CTX[model_path] = Context(model_path)
    return _CTX[model_path]


def _subject_arrays(processed_dir, subject):
    key = (str(processed_dir), subject)
    if key not in _PROC:
        _PROC[key] = dict(np.load(Path(processed_dir) / f"{subject}.npz"))
    return _PROC[key]


# ------------------------------------------------------------------------------ one stride

def run_stride(task: dict) -> dict:
    """Everything the record needs from one subject-stride. `task` is plain data so it can cross a process boundary."""
    c = _ctx(task["model_path"])
    model, mapping = c.model, c.mapping
    z = _subject_arrays(task["processed"], task["subject"])
    sp, i = task["speed"], task["index"]
    ik, idm, fp = z[f"{sp}_ik"][i], z[f"{sp}_id"][i], z[f"{sp}_fp"][i]
    T = float(z[f"{sp}_duration_s"][i])
    sub = task["subject_info"]
    ratio = retarget.leg_length_ratio(model, sub["height_m"])
    mass_ratio = c.mass / sub["mass_kg"]
    cut = task["cutoff_hz"]
    hip = sub.get("hip_in_pelvis_os_m")
    ref = task["root_reference"] if hip is not None else "pelvis_origin"
    cyc = retarget.Cycle(model, mapping, c.stand, ik, T, ratio, cutoff_hz=cut, pitch_offset_deg=task["pitch_offset_deg"],
                         root_rule=task["root_rule"], hip_in_pelvis_os=hip, root_ref=ref,
                         pitch_mean=task["pitch_mean"], trunk=task["trunk"])
    q, qd, qdd = cyc.grid()
    methods = task["methods"]
    joints = c.joints
    nf = N_FRAMES
    ref_xy = np.array([retarget.model_hip_mid(model, q[k])[:2] if ref == "hip_midpoint" else q[k, :2] for k in range(nf)])
    cop_mode = task.get("cop_mode", "hip_reference")
    markers = z[f"{sp}_foot_markers"][i] if cop_mode == "foot_frame" else None

    def measured(frame, k):
        """Measured force and CoP of the loaded feet in the model frame, by the spec's CoP mapping."""
        if cop_mode == "foot_frame":
            return gaitloads.measured_to_model_foot(frame, markers[k], dynamics.foot_floor_segments(model, q[k]), mass_ratio)
        return gaitloads.measured_to_model(frame, ref_lab[k], ref_xy[k], mass_ratio, ratio, task["cop_scale"])
    ftot = np.zeros((nf, 3))  # Freyja's own total ground force, m (a + g): the same for B and H
    tor = {m: np.zeros((nf, len(joints))) for m in methods}
    bound = np.zeros((nf, len(joints)))
    dof = [c.hinge[j][1] for j in joints]
    resid = {m: np.zeros((nf, 6)) for m in methods}
    fpf = gaitloads.filter_measured(fp, T, cut) if "A_filtered" in methods else None
    # reference point of the measured CoP: the midpoint of the dataset model's hip joint centres (or the pelvis origin), unfiltered
    ref_lab = retarget.dataset_hip_mid_lab(ik, hip) if ref == "hip_midpoint" else ik[:, 3:6]
    stance_n = np.zeros(N_BINS); cop_out = np.zeros(N_BINS); fric_out = np.zeros(N_BINS)
    cop_margin_min = np.inf
    by_support = {"single": [0, 0], "double": [0, 0]}  # stance-foot frames, CoP outside
    degenerate_n = 0
    miss = np.zeros(4)  # stance-foot frames with the CoP outside by <10, 10-30, 30-100, >100 mm
    cop_err = []  # single support: B's CoP minus the measured one (scaled), model axes x, y
    share_err = []  # double support: B's right-foot share minus the measured share
    for k in range(nf):
        stance = tuple(f for j, f in enumerate(FEET) if fp[j, k, 6] >= gaitloads.STANCE_FLAG)
        qfrc = dynamics.inverse_frame(model, q[k], qd[k], qdd[k])
        ftot[k] = qfrc[:3]
        if "B" in methods:
            r = dynamics.solve_frame(model, q[k], qd[k], qdd[k], stance=stance, sweep=task["sweep"], qfrc=qfrc)
            tor["B"][k] = [r.torque[j] for j in joints]
            bound[k] = [max(abs(r.torque_range[j][0]), abs(r.torque_range[j][1])) for j in joints]
            resid["B"][k] = r.residual
            b = min(k * N_BINS // nf, N_BINS - 1)
            for foot in stance:
                stance_n[b] += 1
                cop_out[b] += not r.cop_margin_m[foot] >= 0
                fric_out[b] += not r.friction_ratio[foot] <= c.mu
                cop_margin_min = min(cop_margin_min, r.cop_margin_m[foot])
                degenerate_n += r.hull_degenerate[foot]
                if not r.cop_margin_m[foot] >= 0:
                    miss[np.searchsorted([0.010, 0.030, 0.100], -r.cop_margin_m[foot])] += 1
                key = "single" if len(stance) == 1 else "double"
                by_support[key][0] += 1
                by_support[key][1] += not r.cop_margin_m[foot] >= 0
            mf, mc = measured(fp[:, k, :], k)
            if len(stance) == 1 and stance[0] in mc:
                cop_err.append((r.cop[stance[0]] - mc[stance[0]])[:2])
            if len(stance) == 2 and len(mf) == 2 and mf["foot_right"][2] + mf["foot_left"][2] > 0:
                share_err.append(r.split_right - mf["foot_right"][2] / (mf["foot_right"][2] + mf["foot_left"][2]))
        if any(m in methods for m in ("A_native", "A_filtered", "H")):
            for m, frame in (("A_native", fp[:, k, :]), ("A_filtered", None if fpf is None else fpf[:, k, :]), ("H", fp[:, k, :])):
                if m not in methods:
                    continue
                forces, cops = measured(frame, k)
                if m == "H":
                    forces = gaitloads.method_h_forces(qfrc, forces)
                t, res, _ = dynamics.solve_given(model, q[k], qfrc, forces, cops)
                tor[m][k] = [t[j] for j in joints]
                resid[m][k] = res
    qdj = np.stack([qd[:nf, d] for d in dof], axis=1)
    out = {"subject": task["subject"], "speed": sp, "index": i, "duration_s": T, "peaks": {}, "resid": {}, "agree": {}}
    for m in methods:
        out["peaks"][m] = {j: peak_metrics(tor[m][:, a], qdj[:, a]) for a, j in enumerate(joints)}
        r = resid[m]
        fn, hm = np.linalg.norm(r[:, :3], axis=1), np.linalg.norm(r[:, 3:5], axis=1)
        out["resid"][m] = {"force_rms_pct_bw": 100 * float(np.sqrt(np.mean(fn ** 2))) / c.weight, "force_peak_pct_bw": 100 * float(fn.max()) / c.weight,
                           "moment_h_rms_nm": float(np.sqrt(np.mean(hm ** 2))), "moment_h_peak_nm": float(hm.max()),
                           "yaw_rms_nm": float(np.sqrt(np.mean(r[:, 5] ** 2))), "yaw_peak_nm": float(np.abs(r[:, 5]).max())}
        if task["agreement"]:
            out["agree"][m] = {}
            for a, j in enumerate(joints[:len(mapping["joints"])]):
                spec_j = mapping["joints"][j]
                data = spec_j["sign"] * idm[:nf, ic.ID_CHANNELS.index(spec_j["dataset"] + "_moment")] / sub["mass_kg"]
                out["agree"][m][j] = agreement(tor[m][:, a] / c.mass, data)
    if "B" in methods:
        out["bound"] = {j: float(bound[:, a].max()) for a, j in enumerate(joints)}
        out["feas"] = {"stance": stance_n.tolist(), "cop_out": cop_out.tolist(), "friction_out": fric_out.tolist(),
                       "cop_margin_min_m": float(cop_margin_min) if np.isfinite(cop_margin_min) else None,
                       "by_support": by_support, "hull_degenerate": degenerate_n, "miss_bins": miss.tolist(),
                       "cop_err_single": np.array(cop_err).reshape(-1, 2).tolist(), "share_err_double": share_err}
    fm_total = mass_ratio * ((fp[0, :, 0:3] + fp[1, :, 0:3]) @ gaitloads.LAB_TO_MODEL.T)
    out["force"] = force_metrics(ftot, retarget.filter_cycle(fm_total, T, cut)[:nf])  # like for like: the measured force filtered the same way
    out["trunk_peak_deg"] = {j: float(np.degrees(np.abs(q[:nf, c.hinge[j][0]]).max())) for j in TRUNK_ANGLE_JOINTS}
    hips = [q[:nf, c.hinge[j][0]] for j in ("hip_fe_right", "hip_fe_left")]
    out["hip_extension_deg"] = float(-np.degrees(min(h.min() for h in hips)))
    if task["kinematics"]:
        out["limit_fraction"] = retarget.limit_fraction(model, q[:nf])
        gaps = cyc.wrap_gap_deg()
        out["wrap_gap_deg"] = {j: abs(v) for j, v in gaps.items()}
        out["foot"] = retarget.foot_metrics(model, cyc, fp[:, :, 6] >= gaitloads.STANCE_FLAG, float(sp))
    return out


# ------------------------------------------------------------------------------ batch

def _tasks(spec, manifest, model_path, processed, methods, cutoff, pitch_offset, cap, sweep, agreement_on, kin):
    subjects = spec.get("subjects") or list(manifest["subjects"])
    tasks = []
    for speed in spec["speeds_mps"]:
        counts = {s: manifest["subjects"][s]["strides"][str(speed)] for s in subjects}
        for s, idx in capped_indices(counts, cap).items():
            for i in idx:
                tasks.append({"model_path": str(model_path), "processed": str(processed), "subject": s, "speed": str(speed), "index": i,
                              "subject_info": manifest["subjects"][s], "cutoff_hz": cutoff, "pitch_offset_deg": pitch_offset,
                              "root_rule": spec["root_rule"], "root_reference": spec.get("root_reference", "hip_midpoint"), "cop_mode": spec.get("cop_mode", "hip_reference"), "pitch_mean": spec.get("pitch_mean", "measured"),
                              "trunk": spec.get("trunk", "rigid"), "methods": methods, "sweep": sweep, "cop_scale": spec["cop_scale"],
                              "agreement": agreement_on, "kinematics": kin})
    return tasks


def _run_tasks(tasks, workers):
    if workers <= 1 or len(tasks) < 8:
        return [run_stride(t) for t in tasks]
    with ProcessPoolExecutor(max_workers=workers) as ex:
        return list(ex.map(run_stride, tasks, chunksize=4))


def _agg_over(rows, getter, offset_subjects):
    keep = [r["subject"] not in offset_subjects for r in rows]
    return aggregate([getter(r) for r in rows], keep)


def build_results(rows, c: Context, spec) -> dict:
    off = set(spec["offset_subjects"])
    res = {}
    for sp in [str(s) for s in spec["speeds_mps"]]:
        R = [r for r in rows if r["speed"] == sp]
        if not R:
            continue
        methods = list(R[0]["peaks"])
        d = {"n_strides": len(R), "n_strides_without_offset": sum(r["subject"] not in off for r in R), "joints": {}, "bound": {},
             "residual": {}, "agreement": {}, "feasibility": {}, "kinematics": {}}
        for j in c.joints:
            # peak_regeneration_w is the magnitude of the most negative power, so mean / p95 / max read in the same direction
            d["joints"][j] = {m: {**{k: _agg_over(R, lambda r, m=m, j=j, k=k: r["peaks"][m][j][k], off)
                                     for k in ("peak_torque_nm", "peak_speed_rad_s", "peak_power_pos_w")},
                                  "peak_regeneration_w": _agg_over(R, lambda r, m=m, j=j: -r["peaks"][m][j]["peak_power_neg_w"], off)} for m in methods}
            if "bound" in R[0]:
                d["bound"][j] = _agg_over(R, lambda r, j=j: r["bound"][j], off)
        for m in methods:
            d["residual"][m] = {k: _agg_over(R, lambda r, m=m, k=k: r["resid"][m][k], off) for k in R[0]["resid"][m]}
            if R[0]["agree"].get(m):
                d["agreement"][m] = {}
                for j in R[0]["agree"][m]:
                    d["agreement"][m][j] = {k: _agg_over(R, lambda r, m=m, j=j, k=k: r["agree"][m][j][k], off)["all"]["mean"]
                                            for k in ("rms_pct_ptp", "peak_diff", "corr")}
                    d["agreement"][m][j].update({k + "_without_offset": _agg_over(R, lambda r, m=m, j=j, k=k: r["agree"][m][j][k], off)["without_offset"]["mean"]
                                                 for k in ("rms_pct_ptp", "peak_diff", "corr")})
        if "feas" in R[0]:
            stance = np.sum([r["feas"]["stance"] for r in R], axis=0)
            cop = np.sum([r["feas"]["cop_out"] for r in R], axis=0)
            fric = np.sum([r["feas"]["friction_out"] for r in R], axis=0)
            d["feasibility"] = {"stance_foot_frames": int(stance.sum()), "cop_outside_fraction": float(cop.sum() / stance.sum()),
                                "friction_exceeded_fraction": float(fric.sum() / stance.sum()),
                                "cop_outside_by_phase_bin": [float(a / b) if b else None for a, b in zip(cop, stance)],
                                "friction_exceeded_by_phase_bin": [float(a / b) if b else None for a, b in zip(fric, stance)],
                                "stance_frames_by_phase_bin": [int(x) for x in stance],
                                "cop_margin_min_m": float(min(r["feas"]["cop_margin_min_m"] for r in R if r["feas"]["cop_margin_min_m"] is not None))}
            d["feasibility"]["hull_degenerate_fraction"] = float(sum(r["feas"]["hull_degenerate"] for r in R) / stance.sum())
            mb = np.sum([r["feas"]["miss_bins"] for r in R], axis=0)
            d["feasibility"]["cop_outside_by_distance_fraction"] = {lab: float(v / stance.sum()) for lab, v in zip(("lt_10mm", "10_30mm", "30_100mm", "gt_100mm"), mb)}
            for key in ("single", "double"):
                n = sum(r["feas"]["by_support"][key][0] for r in R)
                d["feasibility"][f"cop_outside_fraction_{key}_support"] = (sum(r["feas"]["by_support"][key][1] for r in R) / n) if n else None
            ce = np.array([e for r in R for e in r["feas"]["cop_err_single"]]).reshape(-1, 2)
            if len(ce):
                d["feasibility"]["single_support_cop_error_mean_xy_m"] = ce.mean(axis=0).tolist()
                d["feasibility"]["single_support_cop_error_rms_xy_m"] = np.sqrt((ce ** 2).mean(axis=0)).tolist()
            se = np.array([e for r in R for e in r["feas"]["share_err_double"]])
            if len(se):
                d["feasibility"]["double_support_share_error_mean"] = float(se.mean())
                d["feasibility"]["double_support_share_error_rms"] = float(np.sqrt((se ** 2).mean()))
        d["force"] = {k: _agg_over(R, lambda r, k=k: r["force"][k], off) for k in R[0]["force"]}
        d["trunk_peak_deg"] = {j: _agg_over(R, lambda r, j=j: r["trunk_peak_deg"][j], off) for j in TRUNK_ANGLE_JOINTS}
        ext = np.array([r["hip_extension_deg"] for r in R])
        d["hip_extension"] = {"median_deg": float(np.median(ext)), "p95_deg": float(np.percentile(ext, 95)), "max_deg": float(ext.max()),
                              "stop_deg": -c.hip_stop_deg, "fraction_beyond_stop": float(np.mean(ext > -c.hip_stop_deg))}
        if "limit_fraction" in R[0]:
            d["kinematics"]["limit_fraction_mean"] = {j: float(np.mean([r["limit_fraction"][j] for r in R])) for j in R[0]["limit_fraction"]}
            d["kinematics"]["wrap_gap_flag_deg"] = spec["wrap_gap_flag_deg"]
            d["kinematics"]["wrap_gap_flagged_strides"] = int(sum(max(r["wrap_gap_deg"].values()) > spec["wrap_gap_flag_deg"] for r in R))
            d["kinematics"]["wrap_gap_flagged_by_joint"] = {j: int(sum(r["wrap_gap_deg"][j] > spec["wrap_gap_flag_deg"] for r in R)) for j in R[0]["wrap_gap_deg"]}
            d["kinematics"]["wrap_gap_median_deg"] = {j: float(np.median([r["wrap_gap_deg"][j] for r in R])) for j in R[0]["wrap_gap_deg"]}
            d["kinematics"]["foot"] = {k: _agg_over(R, lambda r, k=k: r["foot"][k], off) for k in R[0]["foot"]}
        res[sp] = d
    return res


def _sensitivity(spec, manifest, model_path, processed, c, workers):
    s = spec["sensitivity"]
    cap = s.get("stride_cap_per_subject")
    out = {"stride_cap_per_subject": cap, "cutoff_hz": {}, "pitch_offset_deg": {}}
    for kind, values, key in (("cutoff_hz", s["cutoffs_hz"], "cutoff_hz"), ("pitch_offset_deg", s["pitch_offsets_deg"], "pitch_offset_deg")):
        for v in values:
            cut = float(v) if kind == "cutoff_hz" else float(spec["smoothing"]["cutoff_hz"])
            tilt = float(v) if kind == "pitch_offset_deg" else float(spec["pelvis_pitch_offset_deg"])
            rows = _run_tasks(_tasks(spec, manifest, model_path, processed, ["B"], cut, tilt, cap, False, False, False), workers)
            by_speed = {}
            for sp in [str(x) for x in spec["speeds_mps"]]:
                R = [r for r in rows if r["speed"] == sp]
                by_speed[sp] = {j: float(np.percentile([r["peaks"]["B"][j]["peak_torque_nm"] for r in R], 95)) for j in c.joints}
            out[kind][str(v)] = by_speed
    return out


def validate(record) -> None:
    import jsonschema
    jsonschema.validate(record, json.loads(SCHEMA_FILE.read_text(encoding="utf-8")))


def _round(x):
    if isinstance(x, dict):
        return {k: _round(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_round(v) for v in x]
    if isinstance(x, (float, np.floating)):
        return None if not np.isfinite(x) else round(float(x), ROUND)
    return x


def run_gait(spec: dict, *, model_path=None, snapshot_path=None, meta_path=None, gait_dir=None, manifest_path=None, processed=None,
             now=None, repo=None, workers=1) -> GaitResult:
    model_path, snapshot_path = Path(model_path or simrun.MODEL_FILE), Path(snapshot_path or simrun.SNAPSHOT_FILE)
    gait_dir = Path(gait_dir or GAIT_DIR)
    manifest_path = Path(manifest_path or REPO / spec["dataset"]["manifest"])
    processed = Path(processed or REPO / spec["dataset"]["processed"])
    gait_id = f"gait.{(now or dt.datetime.now()):%Y%m%d-%H%M}-{spec['name']}"
    model_sha, snapshot_sha = simrun.verify_inputs(model_path, snapshot_path, meta_path or simrun.META_FILE)
    out_dir = gait_dir / gait_id.removeprefix("gait.")
    if out_dir.exists():
        raise GaitError(f"{gait_id} already exists; an id has minute resolution, so wait for the next minute")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    c = _ctx(str(model_path))
    started = []
    tasks = _tasks(spec, manifest, model_path, processed, [m for m in spec["methods"]], float(spec["smoothing"]["cutoff_hz"]),
                   float(spec["pelvis_pitch_offset_deg"]), spec.get("stride_cap_per_subject"), True, True, True)
    if not tasks:
        raise GaitError("the spec selects no strides")
    rows = _run_tasks(tasks, workers)
    results = build_results(rows, c, spec)
    sens = _sensitivity(spec, manifest, model_path, processed, c, workers)
    subjects = {s: {"mass_kg": manifest["subjects"][s]["mass_kg"], "height_m": manifest["subjects"][s]["height_m"],
                    "sex": manifest["subjects"][s]["sex"], "leg_length_ratio": retarget.leg_length_ratio(c.model, manifest["subjects"][s]["height_m"]),
                    "strides": {sp: sum(1 for r in rows if r["subject"] == s and r["speed"] == sp) for sp in [str(x) for x in spec["speeds_mps"]]}}
                for s in sorted({r["subject"] for r in rows})}
    record = {
        "schema": "gait-summary/1", "gait_id": gait_id, **runrecord.git_state(repo),
        "snapshot_sha256": snapshot_sha, "model_sha256": model_sha, "spec_sha256": _sha(spec),
        "dataset_manifest_sha256": hashlib.sha256(manifest_path.read_bytes()).hexdigest(), "env": runrecord.env_versions(),
        "pitch_mean": spec.get("pitch_mean", "measured"), "trunk": spec.get("trunk", "rigid"), "hybrid_methods": hybrid_methods(spec),
        "retarget_version": retarget.VERSION, "dynamics_version": dynamics.VERSION, "gait_version": VERSION,
        "spec": spec,
        "assumptions": [spec["upper_body"], f"root rule {spec['root_rule']}: the dataset's pelvis translation scaled by leg-length ratio",
                        f"pelvis pitch mean: {spec.get('pitch_mean', 'measured')} (anterior-positive offset {spec['pelvis_pitch_offset_deg']} deg); trunk mode: {spec.get('trunk', 'rigid')}",
                        "treadmill: the model walks in place, the belt carries the ground backward; no friction-cone or slip enforcement on the kinematics",
                        "methods A and H take the CoP relative to the subject's pelvis, scaled by leg-length ratio",
                        "joint limits and contacts are disabled in inverse dynamics; frames past a limit are not clipped"],
        "attribution": ATTRIBUTION, "subjects": subjects, "results": results, "sensitivity": sens,
    }
    record = _round(record)
    validate(record)
    out_dir.mkdir(parents=True)
    jp, mp = out_dir / "gait.json", out_dir / "GAIT.md"
    with open(jp, "w", encoding="utf-8", newline="\n") as f:
        f.write(runrecord.dumps(record))
    with open(mp, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_md(record))
    return GaitResult(record, jp, mp)


