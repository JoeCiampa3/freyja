def _tasks(spec, manifest, model_path, processed, methods, cutoff, pitch_offset, cap, sweep, agreement_on, kin, trunk=None):
    trunk = trunk or trunk_modes(spec)[0]
    subjects = spec.get("subjects") or list(manifest["subjects"])
    tasks = []
    for speed in spec["speeds_mps"]:
        counts = {s: manifest["subjects"][s]["strides"][str(speed)] for s in subjects}
        for s, idx in capped_indices(counts, cap).items():
            for i in idx:
                tasks.append({"model_path": str(model_path), "processed": str(processed), "subject": s, "speed": str(speed), "index": i,
                              "subject_info": manifest["subjects"][s], "cutoff_hz": cutoff, "pitch_offset_deg": pitch_offset,
                              "root_rule": spec["root_rule"], "root_reference": spec.get("root_reference", "hip_midpoint"), "cop_mode": spec.get("cop_mode", "hip_reference"), "pitch_mean": spec.get("pitch_mean", "measured"),
                              "pelvis_frame_offset": spec.get("pelvis_frame_offset", "none"), "trunk": trunk, "methods": methods, "sweep": sweep, "cop_scale": spec["cop_scale"],
                              "agreement": agreement_on, "kinematics": kin})
    return tasks


def _run_tasks(tasks, workers):
    if workers <= 1 or len(tasks) < 8:
        return [run_stride(t) for t in tasks]
    with ProcessPoolExecutor(max_workers=workers) as ex:
        return list(ex.map(run_stride, tasks, chunksize=4))


Exclusions = namedtuple("Exclusions", "offset pitch")  # subject sets removed for `without_offset` and for `without_pitch_flagged`


def _agg_over(rows, getter, ex):
    if not isinstance(ex, Exclusions):
        ex = Exclusions(set(ex), set())
    keep = [r["subject"] not in ex.offset for r in rows]
    keep_pitch = [r["subject"] not in ex.pitch for r in rows] if ex.pitch else None
    return aggregate([getter(r) for r in rows], keep, keep_pitch)


def _build_one(R, c: Context, spec, off) -> dict:
    """Every table of one (speed, trunk mode): R holds that cell's subject-strides."""
    methods = list(R[0]["peaks"])
    d = {"n_strides": len(R), "n_strides_without_offset": sum(r["subject"] not in off.offset for r in R), "joints": {}, "bound": {},
         "residual": {}, "agreement": {}, "feasibility": {}, "kinematics": {}}
    if off.pitch:
        d["n_strides_without_pitch_flagged"] = sum(r["subject"] not in off.pitch for r in R)
    for j in c.joints:
        # peak_regeneration_w is the magnitude of the most negative power, so mean / p95 / max read in the same direction
        d["joints"][j] = {m: {**{k: _agg_over(R, lambda r, m=m, j=j, k=k: r["peaks"][m][j][k], off)
                                 for k in ("peak_torque_nm", "peak_speed_rad_s", "peak_power_pos_w")},
                              "peak_regeneration_w": _agg_over(R, lambda r, m=m, j=j: -r["peaks"][m][j]["peak_power_neg_w"], off)} for m in methods}
        if "bound" in R[0]:
            d["bound"][j] = _agg_over(R, lambda r, j=j: r["bound"][j], off)
    for m in methods:
        d["residual"][m] = {k: _agg_over(R, lambda r, m=m, k=k: r["resid"][m][k], off) for k in R[0]["resid"][m]}
        if R[0]["agree"].get(m):
            d["agreement"][m] = {}
            for j in R[0]["agree"][m]:
                d["agreement"][m][j] = {k: _agg_over(R, lambda r, m=m, j=j, k=k: r["agree"][m][j][k], off)["all"]["mean"]
                                        for k in ("rms_pct_ptp", "peak_diff", "corr")}
                d["agreement"][m][j].update({k + "_without_offset": _agg_over(R, lambda r, m=m, j=j, k=k: r["agree"][m][j][k], off)["without_offset"]["mean"]
                                             for k in ("rms_pct_ptp", "peak_diff", "corr")})
                if off.pitch:
                    d["agreement"][m][j].update({k + "_without_pitch_flagged": _agg_over(R, lambda r, m=m, j=j, k=k: r["agree"][m][j][k], off)["without_pitch_flagged"]["mean"]
                                                 for k in ("rms_pct_ptp", "peak_diff", "corr")})
    d["band"] = {m: {"all": band_verdict({j: {"corr": a["corr"], "rms_pct_ptp": a["rms_pct_ptp"]} for j, a in aj.items()}),
                     "without_offset": band_verdict({j: {"corr": a["corr_without_offset"], "rms_pct_ptp": a["rms_pct_ptp_without_offset"]} for j, a in aj.items()})}
                 for m, aj in d["agreement"].items()}
    if off.pitch:
        for m, aj in d["agreement"].items():
            d["band"][m]["without_pitch_flagged"] = band_verdict({j: {"corr": a["corr_without_pitch_flagged"], "rms_pct_ptp": a["rms_pct_ptp_without_pitch_flagged"]} for j, a in aj.items()})
    if "feas" in R[0]:
        stance = np.sum([r["feas"]["stance"] for r in R], axis=0)
        cop = np.sum([r["feas"]["cop_out"] for r in R], axis=0)
        fric = np.sum([r["feas"]["friction_out"] for r in R], axis=0)
        d["feasibility"] = {"support_frames": int(stance.sum()), "cop_outside_fraction": float(cop.sum() / stance.sum()),
                            "friction_exceeded_fraction": float(fric.sum() / stance.sum()),
                            "cop_outside_by_phase_bin": [float(a / b) if b else None for a, b in zip(cop, stance)],
                            "friction_exceeded_by_phase_bin": [float(a / b) if b else None for a, b in zip(fric, stance)],
                            "stance_frames_by_phase_bin": [int(x) for x in stance],
                            "cop_margin_min_m": float(min(r["feas"]["cop_margin_min_m"] for r in R if r["feas"]["cop_margin_min_m"] is not None))}
        d["feasibility"]["hull_degenerate_fraction"] = float(sum(r["feas"]["hull_degenerate"] for r in R) / max(1, sum(r["feas"]["by_support"]["single"][0] for r in R)))
        nom = np.sum([r["feas"]["nominal_rule"] for r in R], axis=0)
        d["feasibility"]["double_support_nominal_rule_placement_fails_fraction"] = float(nom[1] / nom[0]) if nom[0] else None
        d["feasibility"]["double_support_nominal_split_in_feasible_set_fraction"] = float(nom[2] / nom[0]) if nom[0] else None
        d["feasibility"]["polygon"] = {}
        for src in ("B", "measured"):
            d["feasibility"]["polygon"][src] = {}
            for b in R[0]["feas"]["polygon"][src]:
                d["feasibility"]["polygon"][src][b] = {}
                for key in ("single", "double"):
                    v = np.array([x for r in R for x in r["feas"]["polygon"][src][b][key] if x == x])
                    out = v[v > 1e-9]
                    d["feasibility"]["polygon"][src][b][key] = {"frames": int(len(v)), "outside_fraction": float(len(out) / len(v)) if len(v) else None,
                                                 "median_outside_m": float(np.median(out)) if len(out) else None,
                                                 "p95_outside_m": float(np.percentile(out, 95)) if len(out) else None}
        for key in ("single", "double"):
            dd = np.array([x for r in R for x in r["feas"]["outside_m"][key]])
            d["feasibility"][f"outside_distance_{key}_support_m"] = {"median": float(np.median(dd)), "p95": float(np.percentile(dd, 95))} if len(dd) else None
        mb = np.sum([r["feas"]["miss_bins"] for r in R], axis=0)
        d["feasibility"]["cop_outside_by_distance_fraction"] = {lab: float(v / stance.sum()) for lab, v in zip(("lt_10mm", "10_30mm", "30_100mm", "gt_100mm"), mb)}
        for key in ("single", "double"):
            n = sum(r["feas"]["by_support"][key][0] for r in R)
            d["feasibility"][f"cop_outside_fraction_{key}_support"] = (sum(r["feas"]["by_support"][key][1] for r in R) / n) if n else None
        ce = np.array([e for r in R for e in r["feas"]["cop_err_single"]]).reshape(-1, 2)
        if len(ce):
            d["feasibility"]["single_support_cop_error_mean_xy_m"] = ce.mean(axis=0).tolist()
            d["feasibility"]["single_support_cop_error_rms_xy_m"] = np.sqrt((ce ** 2).mean(axis=0)).tolist()
        se = np.array([e for r in R for e in r["feas"]["share_err_double"]])
        if len(se):
            d["feasibility"]["double_support_share_error_mean"] = float(se.mean())
            d["feasibility"]["double_support_share_error_rms"] = float(np.sqrt((se ** 2).mean()))
    d["force"] = {k: _agg_over(R, lambda r, k=k: r["force"][k], off) for k in R[0]["force"]}
    d["trunk_peak_deg"] = {j: _agg_over(R, lambda r, j=j: r["trunk_peak_deg"][j], off) for j in TRUNK_ANGLE_JOINTS}
    ext = np.array([r["hip_extension_deg"] for r in R])
    d["hip_extension"] = {"median_deg": float(np.median(ext)), "p95_deg": float(np.percentile(ext, 95)), "max_deg": float(ext.max()),
                          "stop_deg": -c.hip_stop_deg, "fraction_beyond_stop": float(np.mean(ext > -c.hip_stop_deg))}
    if "limit_fraction" in R[0]:
        d["kinematics"]["limit_fraction_mean"] = {j: float(np.mean([r["limit_fraction"][j] for r in R])) for j in R[0]["limit_fraction"]}
        d["kinematics"]["wrap_gap_flag_deg"] = spec["wrap_gap_flag_deg"]
        d["kinematics"]["wrap_gap_flagged_strides"] = int(sum(max(r["wrap_gap_deg"].values()) > spec["wrap_gap_flag_deg"] for r in R))
        d["kinematics"]["wrap_gap_flagged_by_joint"] = {j: int(sum(r["wrap_gap_deg"][j] > spec["wrap_gap_flag_deg"] for r in R)) for j in R[0]["wrap_gap_deg"]}
        d["kinematics"]["wrap_gap_median_deg"] = {j: float(np.median([r["wrap_gap_deg"][j] for r in R])) for j in R[0]["wrap_gap_deg"]}
        d["kinematics"]["foot"] = {k: _agg_over(R, lambda r, k=k: r["foot"][k], off) for k in R[0]["foot"]}
    return d

def build_results(rows, c: Context, spec) -> dict:
    """results[speed][trunk mode] -> the tables of _build_one."""
    off = Exclusions(set(spec["offset_subjects"]), set(spec.get("pitch_flag_subjects", [])))
    res = {}
    for sp in [str(s) for s in spec["speeds_mps"]]:
        for mode in trunk_modes(spec):
            R = [r for r in rows if r["speed"] == sp and r["trunk"] == mode]
            if R:
                res.setdefault(sp, {})[mode] = _build_one(R, c, spec, off)
    return res


def _sensitivity(spec, manifest, model_path, processed, c, workers):
    """Method B's 95th-percentile peak torque per joint at each cutoff and pitch offset: out[kind][value][mode][speed][joint]."""
    s = spec["sensitivity"]
    cap = s.get("stride_cap_per_subject")
    out = {"stride_cap_per_subject": cap, "cutoff_hz": {}, "pitch_offset_deg": {}}
    for kind, values in (("cutoff_hz", s["cutoffs_hz"]), ("pitch_offset_deg", s["pitch_offsets_deg"])):
        for v in values:
            cut = float(v) if kind == "cutoff_hz" else float(spec["smoothing"]["cutoff_hz"])
            tilt = float(v) if kind == "pitch_offset_deg" else float(spec["pelvis_pitch_offset_deg"])
            out[kind][str(v)] = {}
            for mode in trunk_modes(spec):
                rows = _run_tasks(_tasks(spec, manifest, model_path, processed, ["B"], cut, tilt, cap, False, False, False, trunk=mode), workers)
                by_speed = {}
                for sp in [str(x) for x in spec["speeds_mps"]]:
                    R = [r for r in rows if r["speed"] == sp]
                    by_speed[sp] = {j: float(np.percentile([r["peaks"]["B"][j]["peak_torque_nm"] for r in R], 95)) for j in c.joints}
                out[kind][str(v)][mode] = by_speed
    return out


def validate(record) -> None:
    import jsonschema
    jsonschema.validate(record, json.loads(SCHEMA_FILE.read_text(encoding="utf-8")))


def _round(x):
    if isinstance(x, dict):
        return {k: _round(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_round(v) for v in x]
    if isinstance(x, (float, np.floating)):
        return None if not np.isfinite(x) else round(float(x), ROUND)
    return x


def run_gait(spec: dict, *, model_path=None, snapshot_path=None, meta_path=None, gait_dir=None, manifest_path=None, processed=None,
             now=None, repo=None, workers=1) -> GaitResult:
    model_path, snapshot_path = Path(model_path or simrun.MODEL_FILE), Path(snapshot_path or simrun.SNAPSHOT_FILE)
    if spec.get("pelvis_frame_offset", "none") not in FRAME_OFFSETS:  # refuse an unknown mode before any work (a manifest without the tilt is refused per subject)
        raise GaitError(f"pelvis_frame_offset must be one of {FRAME_OFFSETS}, got {spec['pelvis_frame_offset']!r}")
    gait_dir = Path(gait_dir or GAIT_DIR)
    manifest_path = Path(manifest_path or REPO / spec["dataset"]["manifest"])
    processed = Path(processed or REPO / spec["dataset"]["processed"])
    gait_id = f"gait.{(now or dt.datetime.now()):%Y%m%d-%H%M}-{spec['name']}"
    model_sha, snapshot_sha = simrun.verify_inputs(model_path, snapshot_path, meta_path or simrun.META_FILE)
    out_dir = gait_dir / gait_id.removeprefix("gait.")
    if out_dir.exists():
        raise GaitError(f"{gait_id} already exists; an id has minute resolution, so wait for the next minute")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    c = _ctx(str(model_path))
    started = []
    tasks = [t for mode in trunk_modes(spec)
             for t in _tasks(spec, manifest, model_path, processed, [m for m in spec["methods"]], float(spec["smoothing"]["cutoff_hz"]),
                             float(spec["pelvis_pitch_offset_deg"]), spec.get("stride_cap_per_subject"), True, True, True, trunk=mode)]
    if not tasks:
        raise GaitError("the spec selects no strides")
    rows = _run_tasks(tasks, workers)
    results = build_results(rows, c, spec)
    sens = _sensitivity(spec, manifest, model_path, processed, c, workers)
    subjects = {s: {"mass_kg": manifest["subjects"][s]["mass_kg"], "height_m": manifest["subjects"][s]["height_m"],
                    "sex": manifest["subjects"][s]["sex"], "leg_length_ratio": retarget.leg_length_ratio(c.model, manifest["subjects"][s]["height_m"]),
                    "strides": {sp: sum(1 for r in rows if r["subject"] == s and r["speed"] == sp) for sp in [str(x) for x in spec["speeds_mps"]]}}
                for s in sorted({r["subject"] for r in rows})}
    record = {
        "schema": "gait-summary/1", "gait_id": gait_id, **runrecord.git_state(repo),
        "snapshot_sha256": snapshot_sha, "model_sha256": model_sha, "spec_sha256": _sha(spec),
        "dataset_manifest_sha256": hashlib.sha256(manifest_path.read_bytes()).hexdigest(), "env": runrecord.env_versions(),
        "pitch_mean": spec.get("pitch_mean", "measured"), "trunk": trunk_modes(spec), "hybrid_methods": hybrid_methods(spec),
        "retarget_version": retarget.VERSION, "dynamics_version": dynamics.VERSION, "gait_version": VERSION,
        "spec": spec,
        "assumptions": [spec["upper_body"], f"root rule {spec['root_rule']}: the dataset's pelvis translation scaled by leg-length ratio",
                        f"pelvis pitch mean: {spec.get('pitch_mean', 'measured')} (anterior-positive offset {spec['pelvis_pitch_offset_deg']} deg); trunk mode(s): {', '.join(trunk_modes(spec))}",
                        f"pelvis frame offset: {spec.get('pelvis_frame_offset', 'none')} (the dataset's IK pelvis frame against the model's Dumas pelvis frame; decisions/0004)",
                        "treadmill: the model walks in place, the belt carries the ground backward; no friction-cone or slip enforcement on the kinematics",
                        "methods A and H take the CoP relative to the subject's pelvis, scaled by leg-length ratio",
                        "joint limits and contacts are disabled in inverse dynamics; frames past a limit are not clipped"]
                       + ([toe_text] if (toe_text := toe_assumption(c.model)) else []),
        "attribution": ATTRIBUTION, "subjects": subjects, "results": results, "sensitivity": sens,
    }
    record = _round(record)
    validate(record)
    out_dir.mkdir(parents=True)
    jp, mp = out_dir / "gait.json", out_dir / "GAIT.md"
    with open(jp, "w", encoding="utf-8", newline="\n") as f:
        f.write(runrecord.dumps(record))
    speed_paths = {}
    for name, text in render_files(record).items():
        path = out_dir / name
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        if name != "GAIT.md":
            speed_paths[name[len("GAIT-"):-len(".md")].replace("p", ".")] = path
    return GaitResult(record, jp, mp, speed_paths)


