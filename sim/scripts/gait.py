def aggregate(values, keep, keep_pitch=None) -> dict:
    """Mean, 95th percentile (linear interpolation) and maximum of `values` over all subject-strides, over the subset where `keep` is true
    (the dataset's offset subjects removed) and, when `keep_pitch` is given, over the subset where that is true (the subjects whose IK pelvis
    pitch disagrees with the pelvic markers removed: T9.3). Without `keep_pitch` the result is what it was before T9.3."""
    v, k = np.asarray(values, float), np.asarray(keep, bool)
    stats = lambda x: {"mean": float(x.mean()), "p95": float(np.percentile(x, 95)), "max": float(x.max())}
    out = {"all": stats(v), "without_offset": stats(v[k])}
    if keep_pitch is not None:
        out["without_pitch_flagged"] = stats(v[np.asarray(keep_pitch, bool)])
    return out


def peak_metrics(torque, qvel) -> dict:
    """Peak torque magnitude, peak speed magnitude and the positive and negative peak power over a stride."""
    torque, qvel = np.asarray(torque, float), np.asarray(qvel, float)
    p = torque * qvel
    return {"peak_torque_nm": float(np.abs(torque).max()), "peak_speed_rad_s": float(np.abs(qvel).max()),
            "peak_power_pos_w": float(p.max()), "peak_power_neg_w": float(p.min())}  # the negative one stays negative per stride


def agreement(model_per_kg, data_per_kg) -> dict:
    """Model moment per kg against the dataset's: RMS difference as a percentage of the dataset's peak-to-peak range, the
    difference of the peak magnitudes (model minus data, N m/kg), and the correlation."""
    m, d = np.asarray(model_per_kg, float), np.asarray(data_per_kg, float)
    ptp = np.ptp(d)
    rms = 100.0 * float(np.sqrt(np.mean((m - d) ** 2))) / ptp if ptp > 0 else float("nan")
    corr = float(np.corrcoef(m, d)[0, 1]) if m.std() > 0 and d.std() > 0 else float("nan")
    return {"rms_pct_ptp": rms, "peak_diff": float(np.abs(m).max() - np.abs(d).max()), "corr": corr}


def force_metrics(fb, fm) -> dict:
    """Freyja's total ground force fb against the measured one fm (both (n, 3), model axes x anterior, y left, z up): the vertical
    peak ratio and correlation, and the peak-to-peak ratio and correlation of the fore-aft and lateral components."""
    c = lambda a, b: float(np.corrcoef(a, b)[0, 1])
    return {"vert_peak_ratio": float(fb[:, 2].max() / fm[:, 2].max()), "vert_corr": c(fb[:, 2], fm[:, 2]),
            "ap_ptp_ratio": float(np.ptp(fb[:, 0]) / np.ptp(fm[:, 0])), "ap_corr": c(fb[:, 0], fm[:, 0]),
            "lat_ptp_ratio": float(np.ptp(fb[:, 1]) / np.ptp(fm[:, 1])), "lat_corr": c(fb[:, 1], fm[:, 1])}


def hybrid_methods(spec: dict) -> list:
    """Methods A and H apply a measured force and CoP that belong to the subject's measured posture; with any other pitch mean they
    are a hybrid and not a load, and the record says so. B is unaffected."""
    if spec.get("pitch_mean", "measured") == "measured":
        return []
    return [m for m in spec["methods"] if m.startswith("A") or m == "H"]


FRAME_OFFSETS = ("none", "measured")


def frame_offset_deg(mode: str, info: dict) -> float:
    """The pelvis frame offset delta (degrees) the retargeting applies for a subject: 0 for `none`, the subject's static Dumas-frame tilt minus its
    static IK pitch for `measured` (decisions/0004, point 2; both are stored by the ingestion). A missing tilt is an error, never a silent zero."""
    if mode not in FRAME_OFFSETS:
        raise GaitError(f"pelvis_frame_offset must be one of {FRAME_OFFSETS}, got {mode!r}")
    if mode == "none":
        return 0.0
    tilt, pitch = info.get("static_dumas_tilt_deg"), info.get("static_pelvis_pitch_deg")
    if tilt is None or pitch is None:
        raise GaitError("pelvis_frame_offset: measured needs static_dumas_tilt_deg and static_pelvis_pitch_deg in the dataset manifest "
                        "(rerun `python analysis/ingest_camargo.py`; the subject needs static marker and IK trials)")
    return float(tilt) - float(pitch)


TOE_STOP_TOL_DEG = 0.1  # degrees. An angle within this of a stop counts as at the stop (a reporting threshold; nothing is computed from it)


def toe_stats(model, qpos, stance) -> dict:
    """The free toe over a stride, from the qpos frames (N, nq) and the dataset's stance flags (2, N) of the right and left foot: the peak angle (degrees) and the fraction of
    frames at the flexion stop (the flat toe), at the extension stop and beyond it, over all frames and over the foot's stance frames. The stops are the model's joint range."""
    out = {}
    for f, side in enumerate(("right", "left")):
        j = model.joint(f"toe_{side}")
        theta = np.degrees(qpos[:, int(j.qposadr[0])])
        lo, hi = np.degrees(j.range[0]), np.degrees(j.range[1])
        st = np.asarray(stance[f], bool)
        pick = lambda x, sel: float(np.mean(x[sel])) if sel.any() else None  # noqa: E731
        out[side] = {"peak_deg": float(theta.max()),
                     "at_flexion_stop": pick(theta <= lo + TOE_STOP_TOL_DEG, np.ones_like(st)), "at_extension_stop": pick(theta >= hi - TOE_STOP_TOL_DEG, np.ones_like(st)),
                     "stance_at_flexion_stop": pick(theta <= lo + TOE_STOP_TOL_DEG, st), "stance_at_extension_stop": pick(theta >= hi - TOE_STOP_TOL_DEG, st),
                     "stance_peak_deg": float(theta[st].max()) if st.any() else None}
    return out


def toe_assumption(model):
    """The sentence GAIT.md prints about the toe (None for a model without one): the rule behind every B and H number, accepted at Checkpoint A of Stage 2g (memo 24, Q4)."""
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "toe_right") < 0:
        return None
    return ("toe: the dataset's foot is rigid, so method A holds the toe welded flat (the ankle carries the whole-foot moment); in B and H the toe rolls with its foot "
            "(rolling rule: while the foot is in stance, as the dataset flags it, and pitched heel-up, the toe takes the angle of the foot's sole to the floor, otherwise 0; "
            "low-passed with the other signals). The toe's stiffness and damping do not enter its motion, only the toe joint's own torque row; the ground force acts on the toe "
            "where the CoP is ahead of the hinge. Not a model of a measured toe angle.")


def trunk_modes(spec: dict) -> list:
    """The spec's `trunk` as a list of modes: a name or a list of distinct names from TRUNK_MODES (default rigid)."""
    t = spec.get("trunk", "rigid")
    modes = [t] if isinstance(t, str) else list(t)
    if not modes or len(set(modes)) != len(modes) or any(m not in TRUNK_MODES for m in modes):
        raise GaitError(f"trunk must be one of {TRUNK_MODES} or a list of distinct ones, got {t!r}")
    return modes


def band_verdict(agree: dict) -> dict:
    """The envelope band for one method. `agree` maps a joint name (hip_fe_right, hip_fe_left, knee_right, ...) to {corr, rms_pct_ptp}; each
    sagittal stem pools its two limbs by the mean. No data for a stem is a failure, never a pass."""
    joints = {}
    for stem in BAND_STEMS:
        v = [agree[j] for j in (f"{stem}_right", f"{stem}_left") if j in agree and agree[j]["corr"] is not None and agree[j]["rms_pct_ptp"] is not None]
        if not v:
            joints[stem] = {"corr": None, "rms_pct_ptp": None, "meets": False}
            continue
        corr, rms = float(np.mean([x["corr"] for x in v])), float(np.mean([x["rms_pct_ptp"] for x in v]))
        joints[stem] = {"corr": corr, "rms_pct_ptp": rms, "meets": bool(corr >= BAND_CORR and rms <= BAND_RMS_PCT)}
    return {"meets": all(j["meets"] for j in joints.values()), "joints": joints}


def stride_count(record: dict) -> int:
    """Subject-strides in a record: each counted once, not once per trunk mode."""
    return sum(next(iter(by_mode.values()))["n_strides"] for by_mode in record["results"].values())


def baseline_methods(verdicts: dict) -> dict:
    """verdicts: (speed, mode) -> method -> {meets}. A method is baselined when it meets the band at every speed and trunk mode; the rest
    are reported as findings and not baselined."""
    methods = sorted({m for v in verdicts.values() for m in v})
    ok = [m for m in methods if all(v.get(m, {}).get("meets", False) for v in verdicts.values())]
    return {"baselined": ok, "not_baselined": [m for m in methods if m not in ok]}


def capped_indices(counts: dict, cap) -> dict:
    """The first `cap` stride indices of each subject (all when cap is None)."""
    return {s: list(range(n if cap is None else min(n, int(cap)))) for s, n in counts.items()}


