"""Volume-extractor brief 1, step 11 and the sensitivity of step 8: the section ledger, side-aware directions, and the CLI stops."""
import subprocess
import sys
from pathlib import Path
from types import SimpleNamespace

import numpy as np
import pytest
import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))

from envelope import field, ledger  # noqa: E402
from envelope.synthetic import frustum  # noqa: E402

R, H = 45.0, 300.0


@pytest.fixture(scope="module")
def seg():
    v, f = frustum(R, R, 60, -H - 60)
    return field.build_segment(v, f, length=H, voxel=2.0, z_top=0.0, margin=40.0)


@pytest.fixture(scope="module")
def rows(seg):
    return ledger.rows_for(seg, "right", shells=(0.0, 5.0))


def test_stations_every_10_mm_plus_the_far_end():
    assert ledger.stations(300.0)[:3] == [0.0, 10.0, 20.0] and ledger.stations(300.0)[-1] == 300.0
    st = ledger.stations(398.08)
    assert st[-2] == 390.0 and st[-1] == 398.08


def test_right_thigh_lateral_is_minus_y_and_medial_is_plus_y():
    n = ledger.direction_names("right")
    assert n[0] == "ant" and n[180] == "post" and n[90] == "med" and n[270] == "lat"
    assert n[45] == "ant_med" and n[315] == "ant_lat" and n[135] == "post_med" and n[225] == "post_lat"
    m = ledger.direction_names("left")
    assert m[90] == "lat" and m[270] == "med"


def test_cylinder_rows_have_the_analytic_numbers(rows):
    r = rows[15]
    assert abs(r["area_mm2"] - np.pi * R * R) < 2 * np.pi * R * 1.0
    assert abs(r["cheb_r_mm"] - R) < 1.0
    for k in ("hw_ant_mm", "hw_post_mm", "hw_med_mm", "hw_lat_mm"):
        assert abs(r[k] - R) < 1.0, k
    for k in [k for k in r if k.startswith("r_") and k.endswith("_mm")]:
        assert abs(r[k] - R) < 1.5, k
    assert abs(r["cheb_r_t5_mm"] - (R - 5)) < 1.0 and abs(r["area_t5_mm2"] - np.pi * (R - 5) ** 2) < 2 * np.pi * R


def test_half_widths_are_measured_from_the_axis_not_the_chebyshev_centre(seg):
    # a box shifted 10 mm to +y: the axis sits off-centre, so the half-widths differ by 20 mm while the Chebyshev circle is centred on the box
    from envelope.synthetic import box
    v, f = box(30, 20, (H + 160) / 2, center=(0, 10, -H / 2))
    s = field.build_segment(v, f, length=H, voxel=2.0, z_top=0.0, margin=40.0)
    r = ledger.rows_for(s, "right", shells=(0.0,))[10]
    assert abs(r["hw_med_mm"] - 30) < 1.0 and abs(r["hw_lat_mm"] - 10) < 1.0     # +y is medial: 30 to the wall, 10 to the other wall
    assert abs(r["cheb_cy_mm"] - 10) < 2.0 and abs(r["cheb_r_mm"] - 20) < 1.0


def test_yaml_and_csv_carry_the_banner_and_neither_a_timestamp_nor_an_absolute_path(rows):
    hdr = {"segment": "thigh_R", "length_mm": 300.0}
    y = ledger.to_yaml(hdr, "abc123def456")
    c = ledger.to_csv(rows, "abc123def456")
    for text in (y, c):
        assert text.startswith("# GENERATED by fy envelope build") and "sha256:abc123def456" in text
        assert "\r" not in text and "C:\\" not in text and "/Users/" not in text
    assert yaml.safe_load(y)["segment"] == "thigh_R"
    assert ledger.to_yaml(hdr, "abc123def456") == y                      # deterministic


def run_cli(*args):
    return subprocess.run([sys.executable, str(REPO / "tools" / "fy"), "envelope", *args], capture_output=True, text=True, cwd=REPO)


def test_build_with_a_wrong_vertex_count_stops_and_says_so(tmp_path):
    obj = tmp_path / "short.obj"
    obj.write_text("v 0 0 0\nv 1 0 0\nv 0 1 0\nf 1 2 3\n")
    r = run_cli("build", "--mesh", str(obj), "--out", str(tmp_path / "o"), "--cache-dir", str(tmp_path / "c"))
    assert r.returncode == 3 and "STOP" in r.stderr and "13380" in r.stderr
