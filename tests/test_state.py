import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "sim" / "scripts"))

import state  # noqa: E402


def git(root, *args):
    subprocess.run(["git", *args], cwd=root, check=True, capture_output=True)


@pytest.fixture()
def repo(tmp_path):
    root = tmp_path / "r"
    (root / "docs" / "briefs").mkdir(parents=True)
    (root / "docs" / "memos").mkdir(parents=True)
    (root / "params").mkdir()
    (root / "checks").mkdir()
    (root / "CLAUDE.md").write_text("Read CONVENTIONS.md first.\nCurrent brief: `docs/briefs/b.md`.\n")
    (root / "docs" / "briefs" / "b.md").write_bytes(b"# brief\nline two\n")
    (root / "docs" / "memos" / "memo1-x.md").write_text("m\n")
    (root / "params" / "snapshot.meta.json").write_text(json.dumps({"snapshot_sha256": "a" * 64, "model_sha256": "b" * 64}))
    (root / "checks" / "waivers.yaml").write_text("- check: check.x.y\n  reason: r\n  source: s\n  recorded: 2026-01-01\n  review_by: 2027-01-01\n  confirmed: false\n")
    git(root, "init", "-q")
    git(root, "config", "user.email", "t@example.com")
    git(root, "config", "user.name", "t")
    git(root, "config", "core.autocrlf", "false")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "init")
    return root


def lines(text):
    return text.splitlines()


def test_two_runs_on_the_same_tree_are_byte_identical(repo):
    assert state.generate(repo, run=False) == state.generate(repo, run=False)


def test_the_state_line_follows_the_banner_and_the_file_is_short(repo):
    text = state.generate(repo, run=False)
    ls = lines(text)
    assert ls[0].startswith("<!-- GENERATED by sim/scripts/state.py") and "Do not edit" in ls[0]
    assert ls[1] == "" and ls[2].startswith("STATE: base ")
    assert len(ls) < 120
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo, capture_output=True, text=True, check=True).stdout.strip()
    assert f"STATE: base {head[:12]} | brief sha256:" in ls[2] and "| snapshot sha256:aaaaaaaaaaaa | tests not run | dirty no" in ls[2]


def test_changing_one_byte_of_the_brief_changes_only_what_depends_on_it(repo):
    before = lines(state.generate(repo, run=False))
    p = repo / "docs" / "briefs" / "b.md"
    p.write_bytes(p.read_bytes().replace(b"two", b"twp"))
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "edit the brief")  # committed, so the tree is clean again and only the brief and the base move
    after = lines(state.generate(repo, run=False))
    assert len(before) == len(after)
    changed = {a.split(":")[0].split(" |")[0] for a, b in zip(before, after) if a != b}
    assert changed == {"STATE", "Base commit", "Brief sha256 (line endings normalised to LF)"}


def test_line_endings_do_not_change_the_brief_hash(repo):
    a = state.brief_hash(repo)
    p = repo / "docs" / "briefs" / "b.md"
    p.write_bytes(p.read_bytes().replace(b"\n", b"\r\n"))
    assert state.brief_hash(repo) == a


@pytest.mark.parametrize("how", ["untracked", "modified"])
def test_an_untracked_or_modified_file_makes_the_tree_dirty(repo, how):
    assert "dirty no" in lines(state.generate(repo, run=False))[2]
    if how == "untracked":
        (repo / "new.txt").write_text("x")
    else:
        (repo / "docs" / "memos" / "memo1-x.md").write_text("changed\n")
    ls = lines(state.generate(repo, run=False))
    assert "dirty yes" in ls[2]
    assert any(l.startswith("Diff hash") and ("none" not in l) == (how == "modified") for l in ls)


def test_generating_the_file_does_not_change_the_dirty_state_or_hash(repo):
    (repo / "docs" / "memos" / "memo1-x.md").write_text("changed\n")
    first = state.generate(repo, run=False)
    (repo / "docs" / "STATE.md").write_text(first)  # untracked: excluded
    assert state.generate(repo, run=False) == first
    git(repo, "add", "docs/STATE.md")
    git(repo, "commit", "-q", "-m", "add the state file")
    (repo / "docs" / "STATE.md").write_text(first + "\nstale\n")  # tracked and modified: excluded from the diff hash
    third = lines(state.generate(repo, run=False))
    diff = lambda ls: next(l for l in ls if l.startswith("Diff hash"))
    assert diff(third) == diff(lines(first))  # the same one-file edit, with or without the state file around


def test_waivers_memos_and_briefs_are_listed_from_the_tree(repo):
    text = state.generate(repo, run=False)
    assert "check.x.y" in text and "confirmed false" in text and "2027-01-01" in text
    assert "memo1-x.md" in text and "b.md" in text


def test_a_runner_supplies_test_and_check_results(repo):
    text = state.generate(repo, run=True, runner=lambda root: {"tests": {"passed": 5, "failed": 1, "skipped": 2},
                                                              "checks": [("check.a.b", "gate", "PASS"), ("check.c.d", "advisory", "FAIL")]})
    ls = lines(text)
    assert "tests 5/8" in ls[2]
    assert any("check.a.b" in l and "gate" in l and "PASS" in l for l in ls) and any("check.c.d" in l and "FAIL" in l for l in ls)


def test_a_staged_file_is_clean_and_an_unstaged_or_untracked_one_is_dirty(repo):
    """Stage 2b: `fy state` run after `git add` of the memo reads `dirty no`; anything not staged still makes the tree dirty."""
    memo = repo / "docs" / "memos" / "memo2-y.md"
    memo.write_text("new memo\n")
    assert "dirty yes" in lines(state.generate(repo, run=False))[2]  # untracked
    git(repo, "add", "docs/memos/memo2-y.md")
    assert "dirty no" in lines(state.generate(repo, run=False))[2]  # staged new file
    memo.write_text("edited after staging\n")
    assert "dirty yes" in lines(state.generate(repo, run=False))[2]  # staged, then modified again: the working tree differs from what would be committed
    git(repo, "add", "docs/memos/memo2-y.md")
    assert "dirty no" in lines(state.generate(repo, run=False))[2]
    tracked = repo / "docs" / "memos" / "memo1-x.md"
    tracked.write_text("modified, not staged\n")
    assert "dirty yes" in lines(state.generate(repo, run=False))[2]  # unstaged modification of a tracked file
    git(repo, "add", "docs/memos/memo1-x.md")
    assert "dirty no" in lines(state.generate(repo, run=False))[2]  # staged modification
    (repo / "stray.txt").write_text("x")
    assert "dirty yes" in lines(state.generate(repo, run=False))[2]  # an untracked file beside staged ones
