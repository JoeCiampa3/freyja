"""
Stage 3b T7: the envelope's registry loader reads the bridge's generated companion `components/cad/<segment>.yaml` beside the authored `components/<segment>.yaml`.
A duplicate id or name across the two is an error, a bridge id must be a part id, the generated file carries revision, sha256 and parameter_inputs per component,
and a segment with no companion loads exactly as before.

    python -m pytest tests/test_envelope_cad_registry.py
"""
import copy
import sys
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))

from envelope import registry  # noqa: E402

AUTHORED = {
    "schema": "components/1", "segment": "upper_arm_R",
    "components": [{"id": "part.arm.actuator", "name": "elbow actuator", "status": "designed", "owner": "upper_arm_R", "primitive": {"type": "cylinder", "diameter": 60, "length": 80},
                    "pose": {"tz": -200}, "clearance_mm": 2.0, "mass_kg": 0.5, "source": "hand-typed"}],
}
GENERATED = {
    "schema": "components/1", "segment": "upper_arm_R",
    "components": [{"id": "part.arm.upper_member", "name": "part.arm.upper_member", "status": "designed", "owner": "upper_arm_R", "revision": "p1",
                    "primitive": {"type": "box", "half": [15.0, 15.0, 127.6], "offset": [0.0, 0.0, -127.6]}, "mesh": "../../../../cad/exports/part.arm.upper_member.stl",
                    "clearance_mm": 0.0, "mass_kg": 0.12, "sha256": "a" * 64, "parameter_inputs": "0123456789ab", "source": "cad/sidecars/part.arm.upper_member.json"}],
}


def write(tmp, authored=AUTHORED, generated=GENERATED):
    d = tmp / "data" / "envelope" / "components"
    (d / "cad").mkdir(parents=True)
    if authored is not None:
        (d / "upper_arm_R.yaml").write_text(yaml.safe_dump(authored), encoding="utf-8")
    if generated is not None:
        (d / "cad" / "upper_arm_R.yaml").write_text("# GENERATED by tools/cad pull\n" + yaml.safe_dump(generated), encoding="utf-8")
    return d


def test_the_generated_companion_is_read_beside_the_authored_file(tmp_path):
    d = write(tmp_path)
    reg = registry.find(d, "upper_arm_R")
    assert [c.id for c in reg.components] == ["part.arm.actuator", "part.arm.upper_member"]
    c = reg.components[1]
    assert (c.revision, c.sha256, c.parameter_inputs, c.status) == ("p1", "a" * 64, "0123456789ab", "designed")
    assert c.primitive["type"] == "box" and c.clearance_mm == 0.0 and c.mass_kg == 0.12


def test_a_mesh_path_in_the_companion_resolves_against_the_registry_base(tmp_path):
    d = write(tmp_path)
    reg = registry.find(d, "upper_arm_R")
    c = reg.components[1]
    assert (Path(reg.base) / c.mesh).resolve() == (tmp_path / "cad" / "exports" / "part.arm.upper_member.stl").resolve()


def test_the_companion_alone_loads_when_there_is_no_authored_file(tmp_path):
    d = write(tmp_path, authored=None)
    reg = registry.find(d, "upper_arm_R")
    assert [c.id for c in reg.components] == ["part.arm.upper_member"]
    assert (Path(reg.base) / reg.components[0].mesh).resolve() == (tmp_path / "cad" / "exports" / "part.arm.upper_member.stl").resolve()


def test_no_file_at_all_is_none_and_an_authored_only_segment_is_unchanged(tmp_path):
    d = write(tmp_path, generated=None)
    assert registry.find(d, "nowhere_R") is None
    assert registry.find(d, "upper_arm_R").to_dict() == registry.load(d / "upper_arm_R.yaml").to_dict()


def test_the_real_thigh_registry_loads_exactly_as_before():
    d = REPO / "data" / "envelope" / "components"
    assert registry.find(d, "thigh_R").to_dict() == registry.load(d / "thigh_R.yaml").to_dict()


def dup(field):
    g = copy.deepcopy(GENERATED)
    g["components"][0][field] = AUTHORED["components"][0][field]
    return g


@pytest.mark.parametrize("field", ["id", "name"])
def test_a_duplicate_id_or_name_across_the_two_files_is_an_error_naming_both(tmp_path, field):
    d = write(tmp_path, generated=dup(field))
    with pytest.raises(registry.RegistryError, match=rf"{field}.*upper_arm_R.yaml.*cad"):
        registry.find(d, "upper_arm_R")


def test_a_bridge_id_must_be_a_part_id(tmp_path):
    g = copy.deepcopy(GENERATED)
    g["components"][0]["id"] = "actuator-9"
    with pytest.raises(registry.RegistryError, match="part id"):
        registry.find(write(tmp_path, generated=g), "upper_arm_R")


@pytest.mark.parametrize("field", ["revision", "sha256", "parameter_inputs"])
def test_the_generated_file_must_carry_revision_sha256_and_parameter_inputs(tmp_path, field):
    g = copy.deepcopy(GENERATED)
    del g["components"][0][field]
    with pytest.raises(registry.RegistryError, match=field):
        registry.find(write(tmp_path, generated=g), "upper_arm_R")


def test_a_companion_for_another_segment_is_refused(tmp_path):
    g = copy.deepcopy(GENERATED)
    g["segment"] = "forearm_R"
    with pytest.raises(registry.RegistryError, match="segment"):
        registry.find(write(tmp_path, generated=g), "upper_arm_R")


def test_the_authored_file_may_carry_the_new_fields_and_a_round_trip_keeps_them(tmp_path):
    a = copy.deepcopy(AUTHORED)
    a["components"][0].update(revision="r2", sha256="b" * 64, parameter_inputs="ffffffffffff")
    p = tmp_path / "x.yaml"
    p.write_text(yaml.safe_dump(a), encoding="utf-8")
    reg = registry.load(p)
    assert (reg.components[0].revision, reg.components[0].sha256) == ("r2", "b" * 64)
    assert reg.to_dict()["components"][0]["revision"] == "r2" and reg.to_dict()["components"][0]["parameter_inputs"] == "ffffffffffff"


def test_the_committed_placeholder_registry_loads_and_its_mesh_is_the_tracked_stl():
    d = REPO / "data" / "envelope" / "components"
    reg = registry.find(d, "upper_arm_R")
    (c,) = [c for c in reg.components if c.id == "part.arm.upper_member"]
    assert (Path(reg.base) / c.mesh).resolve() == (REPO / "cad" / "exports" / "part.arm.upper_member.stl").resolve()
    assert (Path(reg.base) / c.mesh).is_file() and c.revision == "p1" and len(c.sha256) == 64


def test_components_know_the_file_they_came_from_and_the_origin_is_not_data(tmp_path):
    d = write(tmp_path)
    reg = registry.find(d, "upper_arm_R")
    assert [c.origin.parent.name for c in reg.components] == ["components", "cad"]
    assert reg.origins() == [d / "upper_arm_R.yaml", d / "cad" / "upper_arm_R.yaml"]
    assert all("origin" not in c for c in reg.to_dict()["components"])


@pytest.mark.skipif(not (REPO / "data" / "envelope" / "cache" / "upper_arm_R.npz").is_file(), reason="the upper arm's voxel field is not built here (cache is gitignored)")
def test_fy_envelope_check_reports_a_margin_for_the_placeholder_and_names_the_generated_file(capsys):
    from envelope import cli
    ex = REPO / "data" / "envelope" / "examples"
    code = cli.main(["check", "--segment", "upper_arm_R", "--shapes", str(ex / "upper_arm_cylinder_shapes.yaml"), "--poses", str(ex / "upper_arm_cylinder_feasible_poses.csv"), "--occupied"],
                    default_root=REPO)
    out = capsys.readouterr().out
    assert "components (data/envelope/components/cad/upper_arm_R.yaml): 1 placed" in out
    assert "part.arm.upper_member [designed]: margin" in out and "binding constraint:" in out and "confidence:" in out
    assert code in (0, 1)
