"""
Roadmap T1: the node front-matter schema and the generated-state schema (docs/schemas/roadmap-node-1.schema.json, roadmap-state-2.schema.json).

Run from the repo root:
    python -m pytest tests/test_roadmap_schema.py
"""
import copy
import json
import re
from pathlib import Path

import jsonschema
import pytest

REPO = Path(__file__).resolve().parents[1]
SCHEMAS = REPO / "docs" / "schemas"


def load(name):
    return json.loads((SCHEMAS / name).read_text(encoding="utf-8"))


NODE = load("roadmap-node-1.schema.json") if (SCHEMAS / "roadmap-node-1.schema.json").exists() else None

# the example in the brief
EXAMPLE = {
    "schema": "roadmap-node/1", "id": "rm.elbow-actuator-selected", "title": "Elbow actuator selected and decision recorded",
    "parent": "rm.upper-arm-v1-tested", "blocked_by": ["rm.upper-arm-loads-final"], "estimate_days": 2, "tags": ["arm", "actuation"],
    "done_when": {"type": "decision", "record": "decisions/0012-elbow-actuator.md"}, "active": False,
}


def errors(doc):
    return list(jsonschema.Draft202012Validator(NODE).iter_errors(doc))


def test_schema_files_exist_and_are_valid_schemas():
    for name in ("roadmap-node-1.schema.json", "roadmap-state-2.schema.json"):
        assert (SCHEMAS / name).exists(), name
        jsonschema.Draft202012Validator.check_schema(load(name))


def test_the_brief_example_is_accepted():
    assert errors(EXAMPLE) == []


@pytest.mark.parametrize("done_when", [
    {"type": "artifact", "path": "records/x.json"},
    {"type": "artifact", "path": "records/x.json", "schema": "docs/schemas/gait-extract-1.schema.json"},
    {"type": "decision", "record": "decisions/0001-toe-joint.md"},
    {"type": "check", "check": "check.mjcf.mirror"},
    {"type": "metric", "record": "sim/benchmarks/walk_reference.json", "pointer": "/a/0", "op": "<=", "value": 0.15, "units": "fraction"},
    {"type": "manual"},
])
def test_every_done_when_type_is_accepted(done_when):
    assert errors({**EXAMPLE, "done_when": done_when}) == []


def test_a_stub_root_and_a_minimal_node_are_accepted():
    assert errors({"schema": "roadmap-node/1", "id": "rm.root", "title": "Freyja v1 walks", "parent": None}) == []
    assert errors({"schema": "roadmap-node/1", "id": "rm.s", "title": "t", "parent": "rm.root", "stub": True, "signed_off": False,
                   "superseded_by": "rm.t"}) == []


def bad(**change):
    doc = copy.deepcopy(EXAMPLE)
    for k, v in change.items():
        if v is KeyError:
            del doc[k]
        else:
            doc[k] = v
    return doc


@pytest.mark.parametrize("name,doc", [
    ("unknown field", bad(colour="red")),
    ("wrong schema tag", bad(schema="roadmap-node/2")),
    ("missing schema", bad(schema=KeyError)),
    ("missing id", bad(id=KeyError)),
    ("missing title", bad(title=KeyError)),
    ("missing parent", bad(parent=KeyError)),
    ("empty title", bad(title="")),
    ("id without the rm. prefix", bad(id="elbow")),
    ("id with upper case", bad(id="rm.Elbow")),
    ("id with a dot in the slug", bad(id="rm.a.b")),
    ("parent that is not an id", bad(parent="upper arm")),
    ("blocked_by not a list", bad(blocked_by="rm.x")),
    ("blocked_by entry not an id", bad(blocked_by=["x"])),
    ("estimate negative", bad(estimate_days=-1)),
    ("estimate zero", bad(estimate_days=0)),
    ("estimate a string", bad(estimate_days="2")),
    ("stub not a bool", bad(stub="yes")),
    ("active not a bool", bad(active=1)),
    ("tags not strings", bad(tags=[1])),
    ("done_when unknown type", bad(done_when={"type": "vibes"})),
    ("done_when without type", bad(done_when={"record": "x"})),
    ("decision without record", bad(done_when={"type": "decision"})),
    ("check without check id", bad(done_when={"type": "check", "check": "mirror"})),
    ("metric without pointer", bad(done_when={"type": "metric", "record": "r.json", "op": "<", "value": 1})),
    ("metric pointer not starting with /", bad(done_when={"type": "metric", "record": "r.json", "pointer": "a", "op": "<", "value": 1})),
    ("metric bad op", bad(done_when={"type": "metric", "record": "r.json", "pointer": "/a", "op": "!=", "value": 1})),
    ("metric value a string", bad(done_when={"type": "metric", "record": "r.json", "pointer": "/a", "op": "<", "value": "1"})),
    ("manual with extra field", bad(done_when={"type": "manual", "note": "x"})),
    ("artifact with an absolute path", bad(done_when={"type": "artifact", "path": "/etc/passwd"})),
    ("artifact with a parent-directory path", bad(done_when={"type": "artifact", "path": "../x"})),
])
def test_each_schema_level_error_is_rejected(name, doc):
    assert errors(doc), name


def test_the_state_schema_accepts_a_minimal_document_and_rejects_a_bad_status():
    schema = load("roadmap-state-2.schema.json")
    v = jsonschema.Draft202012Validator(schema)
    doc = {"_generated": "GENERATED by x", "generated_by": "tools/roadmap", "inputs": [], "schema": "roadmap-state/2", "node_count": 0,
           "superseded_count": 0, "counts": {}, "frontier": [], "errors": [], "warnings": [], "nodes": {}}
    assert list(v.iter_errors(doc)) == []
    node = {"title": "t", "path": "roadmap/nodes/rm.a.md", "kind": "leaf", "status": "ready", "reason": "r", "parent": None, "children": [],
            "blocked_by": [], "effective_blockers": [], "uncleared_blockers": [], "dependents": [], "estimate_days": 1, "tags": [],
            "active": False, "signed_off": False, "superseded_by": None, "done_when": {"type": "manual"},
            "evaluation": {"result": "fail", "reason": "not signed off", "measured": None}}
    assert list(v.iter_errors({**doc, "node_count": 1, "counts": {"ready": 1}, "nodes": {"rm.a": node}})) == []
    broken = {**doc, "node_count": 1, "nodes": {"rm.a": {**node, "status": "cooked"}}}
    assert list(v.iter_errors(broken))
    # 'stale' is reserved: the schema allows the name, the library never emits it
    assert list(v.iter_errors({**doc, "node_count": 1, "nodes": {"rm.a": {**node, "status": "stale"}}})) == []


def test_every_schema_file_follows_the_name_pattern():
    """Joe's T5b(d): `<name>-<version>.schema.json`, as the run, sweep and gait schemas are named."""
    names = sorted(p.name for p in SCHEMAS.glob("*.json"))
    assert names and all(re.fullmatch(r"[a-z]+(-[a-z]+)*-\d+\.schema\.json", n) for n in names), names
    assert {"roadmap-node-1.schema.json", "roadmap-state-2.schema.json"} <= set(names)


def test_the_state_schema_is_version_2_and_names_every_evaluation_result():
    """Brief 2 T2: the evaluation results are exactly pass, fail, awaiting, unknown, and the version moved with the enum."""
    schema = load("roadmap-state-2.schema.json")
    assert schema["$id"] == "roadmap-state/2" and schema["properties"]["schema"] == {"const": "roadmap-state/2"}
    ev = schema["$defs"]["node"]["properties"]["evaluation"]["properties"]["result"]
    assert ev["enum"] == ["pass", "fail", "awaiting", "unknown"]
