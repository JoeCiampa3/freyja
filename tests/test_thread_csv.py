"""
CSV addressing (docs/briefs/ariadne/upper-arm-characterization-brief.md, T3; gates G-S5, G-S6). A tracked CSV is an address source: its value
is {first-column cell: {header: cell}}, `#` lines skipped, every cell the string as written, so a hash is the text's.
`data/envelope/upper_arm_R_sections.csv#/40.0/hw_lat_mm` is one cell.

    python -m pytest tests/test_thread_csv.py
"""
import json
from pathlib import Path

import pytest
from thread_help import REPO, make_root, write_record

from thread import addr, build, store

CSV = "# GENERATED by a test. Do not edit.\ns_mm,area_mm2,hw_lat_mm\n0.0,21.8,0.0\n40.0,3051.5,34.30\n50.0,3100.0,35.10\n"
REL = "data/envelope/x_sections.csv"


def root_with(tmp_path, text=CSV):
    root = make_root(tmp_path / "r")
    p = root / REL
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")
    return root


def resolve(root, a):
    return build.build_root(root).resolve(a)


def why(root, a):
    return build.build_root(root).why_unresolved(a)


# ---- G-S6 ------------------------------------------------------------------------------


def test_a_cell_resolves_to_its_string_as_written(tmp_path):
    root = root_with(tmp_path)
    assert resolve(root, f"{REL}#/40.0/hw_lat_mm") == (True, "34.30")
    assert resolve(root, f"{REL}#/0.0/hw_lat_mm") == (True, "0.0")


def test_a_row_resolves_to_a_mapping_of_header_to_cell(tmp_path):
    root = root_with(tmp_path)
    assert resolve(root, f"{REL}#/50.0") == (True, {"s_mm": "50.0", "area_mm2": "3100.0", "hw_lat_mm": "35.10"})


def test_the_whole_file_is_keyed_by_the_first_column_and_comments_are_skipped(tmp_path):
    ok, doc = resolve(root_with(tmp_path), f"{REL}#")
    assert ok and sorted(doc) == ["0.0", "40.0", "50.0"] and not any(k.startswith("#") for k in doc)


def test_the_hash_is_the_texts_not_a_numbers(tmp_path):
    a = build.build_root(root_with(tmp_path / "a")).address_hash(f"{REL}#/40.0/hw_lat_mm")
    b = build.build_root(root_with(tmp_path / "b", CSV.replace("34.30", "34.3"))).address_hash(f"{REL}#/40.0/hw_lat_mm")
    assert a == addr.hash_value("34.30") and a != b


def test_editing_another_row_leaves_the_hash_alone(tmp_path):
    a = build.build_root(root_with(tmp_path / "a")).address_hash(f"{REL}#/40.0/hw_lat_mm")
    b = build.build_root(root_with(tmp_path / "b", CSV.replace("35.10", "99.99"))).address_hash(f"{REL}#/40.0/hw_lat_mm")
    c = build.build_root(root_with(tmp_path / "c", CSV.replace("3051.5", "3000.0"))).address_hash(f"{REL}#/40.0/hw_lat_mm")
    assert a == b == c


def test_editing_the_cell_changes_the_hash(tmp_path):
    a = build.build_root(root_with(tmp_path / "a")).address_hash(f"{REL}#/40.0/hw_lat_mm")
    b = build.build_root(root_with(tmp_path / "b", CSV.replace("34.30", "34.31"))).address_hash(f"{REL}#/40.0/hw_lat_mm")
    assert a != b


def test_a_missing_row_fails_naming_the_file_and_the_key(tmp_path):
    root = root_with(tmp_path)
    assert resolve(root, f"{REL}#/45.0/hw_lat_mm") == (False, None)
    msg = why(root, f"{REL}#/45.0/hw_lat_mm")
    assert REL in msg and "'45.0'" in msg and "row" in msg


def test_a_missing_column_fails_naming_the_file_and_the_key(tmp_path):
    root = root_with(tmp_path)
    assert resolve(root, f"{REL}#/40.0/hw_med_mm") == (False, None)
    msg = why(root, f"{REL}#/40.0/hw_med_mm")
    assert REL in msg and "'hw_med_mm'" in msg and "'40.0'" in msg and "column" in msg


def test_a_duplicate_first_column_key_fails_naming_the_file_and_the_key(tmp_path):
    root = root_with(tmp_path, CSV + "40.0,1.0,2.0\n")
    assert resolve(root, f"{REL}#/0.0/hw_lat_mm") == (False, None)  # the file does not parse, so no address into it resolves
    msg = why(root, f"{REL}#/0.0/hw_lat_mm")
    assert REL in msg and "'40.0'" in msg and "duplicate" in msg


@pytest.mark.parametrize("text, words", [("# only a comment\n", "no header"), ("a,b,a\n1,2,3\n", "'a' twice"), ("a,b\n1,2,3\n", "'1'")])
def test_a_malformed_file_fails_naming_the_file(tmp_path, text, words):
    root = root_with(tmp_path, text)
    msg = why(root, f"{REL}#")
    assert REL in msg and words in msg


def test_a_resolvable_address_has_no_reason(tmp_path):
    assert why(root_with(tmp_path), f"{REL}#/40.0/hw_lat_mm") is None


def test_a_work_item_consuming_a_missing_cell_is_warned_with_the_reason_and_stamping_refuses(tmp_path):
    root = root_with(tmp_path)
    write_record(root, id="work.w", kind="work_item", of="seg.pelvis", mode="assisted", consumes=[f"{REL}#/45.0/hw_lat_mm"])
    b = build.build_root(root)
    w = [i.message for i in b.warnings if i.code == "address-unresolved"]
    assert any(REL in m and "'45.0'" in m for m in w)
    with pytest.raises(ValueError, match=r"45\.0"):
        build.write_stamp(root, b, "work.w", stamp="20260101-0000", by="test")


def test_a_record_addressing_an_unparsable_csv_is_a_build_error_naming_the_record_file_and_key(tmp_path):
    """Joe's answer 5 to memo 62: a CSV that a record or stamp addresses and that does not parse is a build error naming the file and the key."""
    root = root_with(tmp_path, CSV + "40.0,1.0,2.0\n")
    write_record(root, id="work.w", kind="work_item", of="seg.pelvis", mode="assisted", consumes=[f"{REL}#/0.0/hw_lat_mm"])
    b = build.build_root(root)
    errs = [i for i in b.errors if i.code == "csv-unparsable"]
    assert len(errs) == 1 and errs[0].ids == ("work.w",)
    m = errs[0].message
    assert "work.w" in m and REL in m and "'40.0'" in m and "duplicate" in m and f"{REL}#/0.0/hw_lat_mm" in m
    assert b.outputs == {}


def test_an_unparsable_csv_that_nothing_addresses_is_not_an_error(tmp_path):
    b = build.build_root(root_with(tmp_path, CSV + "40.0,1.0,2.0\n"))
    assert b.errors == [] and b.warnings == []


def test_a_missing_row_or_column_stays_a_warning_not_an_error(tmp_path):
    root = root_with(tmp_path)
    write_record(root, id="work.w", kind="work_item", of="seg.pelvis", mode="assisted", consumes=[f"{REL}#/45.0/hw_lat_mm", f"{REL}#/40.0/hw_med_mm"])
    b = build.build_root(root)
    assert b.errors == [] and [i.code for i in b.warnings] == ["address-unresolved"]


def test_a_work_item_consuming_a_cell_is_stamped_and_goes_stale_on_that_cell_only(tmp_path):
    root = root_with(tmp_path)
    write_record(root, id="work.w", kind="work_item", of="seg.pelvis", mode="assisted", consumes=[f"{REL}#/40.0/hw_lat_mm"])
    build.write_stamp(root, build.build_root(root), "work.w", stamp="20260101-0000", by="test")
    assert build.build_root(root).work["work.w"]["status"] == "current"
    (root / REL).write_text(CSV.replace("35.10", "36.00"), encoding="utf-8", newline="\n")
    assert build.build_root(root).work["work.w"]["status"] == "current"
    (root / REL).write_text(CSV.replace("34.30", "34.40"), encoding="utf-8", newline="\n")
    b = build.build_root(root)
    assert b.work["work.w"]["status"] == "stale" and b.work["work.w"]["moved"][0]["current"] == "34.40"


