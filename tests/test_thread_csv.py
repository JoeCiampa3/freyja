def _addresses(b):
    found = set()

    def walk(x):
        if isinstance(x, dict):
            for v in x.values():
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)
        elif isinstance(x, str):
            try:
                addr.parse(x)
            except ValueError:
                return
            found.add(x)
    for r in b.store.records.values():
        walk(r)
    return found


def test_gs5_every_recorded_hash_still_matches():
    """Every address a stamp or a CAD sidecar recorded with its hash resolves to that hash; the work item stays current."""
    b = build.build_root(REPO)
    pairs = [(c["address"], c["hash"]) for lst in b.store.stamps.values() for _, doc in lst for c in doc["consumes"]]
    for p in sorted((REPO / "cad" / "sidecars").glob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        pairs += [(c["address"], c["hash"]) for c in d.get("consumes", [])]
        pairs += [(q["address"], q["address_hash"]) for q in d.get("parameters", []) if "address" in q]
    assert pairs and all(b.address_hash(a) == h for a, h in pairs)
    assert all(b.resolve(a)[0] for a in _addresses(b))
    assert b.work["work.upper-arm-cad"]["status"] == "current"
